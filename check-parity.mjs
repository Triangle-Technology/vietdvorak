// is refused here instead, at load, naming the field and the row.
const CASE_TABLES = [
  ['SCORING_CASES', () => SCORING_CASES, 31,
    'the constructed slip cases — one row per KIND of mistake, plus the WPM, paint and Backspace rows',
    expectRowProblem],
  ['NOOP_CASES', () => NOOP_CASES, 2,
    'the keys the engine swallows: nothing typed, so nothing counted', noopRowProblem],
  ['POSITION_CASES', () => POSITION_CASES, 8,
    'the same slip charged the same early and late — round 5', positionRowProblem],
  ['SEVERITY_CASES', () => SEVERITY_CASES, 1,
    'more mistakes must read worse — round 4', severityRowProblem],
];

// Every field a row may assert, and the ONE list of them. It is checked against
// the object snapshot() really returns before any case runs (see checkScoring),
// so it cannot quietly go stale — which matters, because it is what makes a
// misspelled field name catchable at all.
const SNAPSHOT_FIELDS = [
  'text', 'keys', 'typed', 'attempts', 'errors', 'accuracy', 'wpm',
  'wordIdx', 'ended', 'border', 'notice', 'hints', 'paint', 'marked',
];

// What each table's rows have to carry to be doing anything. One function per
// table because the tables assert in different ways: SCORING_CASES names fields,
// NOOP_CASES compares a state with itself either side of one key, POSITION_CASES
// compares two runs, SEVERITY_CASES compares two error counts.
const isText = (v) => typeof v === 'string' && v.length > 0;
const isScript = (v) => isText(v) || (Array.isArray(v) && v.length > 0 && v.every(isText));

function expectRowProblem(row) {
  if (!isScript(row.target)) return 'has no target word (or list of words) to type at';
  if (!isText(row.keys)) return 'has no `keys` script, so it types nothing';
  const want = row.expect;
  if (!want || typeof want !== 'object' || Array.isArray(want)) {
    return 'has no `expect` object — it types its script and then asserts nothing';
  }
  const named = Object.keys(want);
  if (named.length === 0) {
    return 'has `expect: {}`: it names no field, and expectationProblems() only looks at the\n'
      + '            fields a row NAMES — so this row types its whole script and cannot fail';
  }
  const unknown = named.filter(f => !SNAPSHOT_FIELDS.includes(f));
  if (unknown.length) {
    return `expects field(s) snapshot() does not produce: ${unknown.join(', ')}\n`
      + `            The readable ones are: ${SNAPSHOT_FIELDS.join(', ')}`;
  }
  return null;
}

function noopRowProblem(row) {
  if (!isScript(row.target)) return 'has no target word to type at';
  if (!isText(row.prefix)) return 'has no `prefix` to type before the swallowed key, so there is no state to compare';
  if (typeof row.key !== 'string' || [...row.key].length !== 1) {
    return 'has no single `key` to press — the case IS "press this one key and nothing may move"';
  }
  return null;
}

function positionRowProblem(row) {
  if (!isScript(row.target)) return 'has no target';
  if (!isText(row.early) || !isText(row.late)) return 'needs both an `early` and a `late` keystroke script to compare';
  if (row.early === row.late) return 'types the same script twice, so it compares a run with itself';
  return null;
}

function severityRowProblem(row) {
  if (!isScript(row.target)) return 'has no target';
  if (!isText(row.one) || !isText(row.many)) return 'needs both a `one` and a `many` keystroke script';
  if (!Number.isInteger(row.oneErrors) || !Number.isInteger(row.manyErrors)) {
    return 'needs `oneErrors` and `manyErrors` as whole numbers — they are the charge each run must attract';
  }
  if (row.manyErrors <= row.oneErrors) {
    return `claims the worse run costs ${row.manyErrors} and the better one ${row.oneErrors}; this table exists to `
      + 'show that MORE mistakes read worse, and a row where they do not compares nothing';
  }
  return null;
}

const TABLE_STAKES =
    '            Four of the last five defects in this project lived in the scoring\n'
  + '            layer, and each of them is a row in one of these tables. A table that\n'
  + '            has lost its rows still PRINTS a count on the PASS line, which is\n'
  + '            exactly how a green run on nothing happens.\n';

function assertCaseTables() {
  for (const [name, get, floor, what, rowProblem] of CASE_TABLES) {
    const table = get();
    if (!Array.isArray(table)) {
      die(`${name} is not an array any more — ${what}.\n${TABLE_STAKES}`);
    }
    if (table.length === 0) {
      die(`${name} IS EMPTY — ${what}.\n`
        + '            Every case it held has stopped running, and this file would otherwise\n'
        + `            print "0 case(s)" as part of a PASS.\n${TABLE_STAKES}`);
    }
    if (table.length < floor) {
      die(`${name} has ${table.length} row(s); this file claims at least ${floor}.\n`
        + `            ${what}.\n`
        + '            Rows have gone missing, or one was deleted without the floor in\n'
        + '            CASE_TABLES being lowered with it. Lower it in the same commit and say\n'
        + `            why the case is no longer worth running.\n${TABLE_STAKES}`);
    }
    const ids = table.map(row => (row && typeof row.id === 'string' ? row.id : ''));
    const blank = ids.indexOf('');
    if (blank >= 0) {
      die(`${name} row ${blank} has no id. Every failure this file prints is named after\n`
        + '            that id, so a row without one reports a fault nobody can locate.');
    }
    const dupes = [...new Set(ids.filter((id, i) => ids.indexOf(id) !== i))];
    if (dupes.length) {
      die(`${name} has duplicate id(s): ${dupes.join(', ')}.\n`
        + '            Two rows answering to one name means a failure points at the wrong one —\n'
        + '            and a table whose rows were replaced by copies of a single row passes\n'
        + '            the count while testing one thing.');
    }
    // ...and whether each row asserts ANYTHING. A table of rows that assert
    // nothing passes every check above and prints its count on the PASS line.
    for (let i = 0; i < table.length; i++) {
      const problem = rowProblem(table[i]);
      if (problem) {
        die(`${name} row ${i} "${ids[i]}" ${problem}.\n`
          + `            ${what}.\n`
          + '            A row that asserts nothing still runs, still counts towards the floor\n'
          + `            and still prints as part of "${table.length} case(s)" on the PASS line.\n${TABLE_STAKES}`);
      }
    }
  }
}

// AT LOAD, before a single file is read, and deliberately not from inside
// checkScoring(): a guard that runs late can be shadowed by whatever fails
// first, and the failure this one exists to catch — four gutted tables — was
// demonstrated alongside three live defects in practice.html. --sync-selftests
// refuses too, on purpose: a file whose coverage has silently gone to zero has
// no business rewriting the trainer's embedded vectors either.
assertCaseTables();

function expectationProblems(id, got, want) {
  const bad = [];
  for (const [field, wanted] of Object.entries(want)) {
    let actual = got[field];
    if (field === 'hints') actual = got.hints > 0 ? 'some' : 'none';
    if (actual !== wanted) {
      bad.push(`${id}: ${field} is ${JSON.stringify(actual)}, expected ${JSON.stringify(wanted)}`);
    }
  }
  return bad;
}

// Runs everything above and returns { failures, counts }. Counts are what the
// PASS line prints, and they are ASSERTED rather than merely reported — the four
// case tables by assertCaseTables(), which runs at load before this is ever
// called, and the sweep against `expectedTargets` below. A table that lost its
// rows must not read as a clean run.
function checkScoring(html, expectedTargets) {
  const h = loadPracticePage(html);
  const { page, press, setWords, snapshot } = h;
  const failures = [];
  // SNAPSHOT_FIELDS is what assertCaseTables() validates every row's `expect`
  // against, at load, before this file is ever read — so it has to be the truth
  // about what snapshot() returns, and it is proved to be here rather than
  // maintained by hand. A field added to snapshot() and not to the list would be
  // unassertable; one removed from snapshot() and left in the list would let a
  // row name a field nothing produces, which is the exact hole the row check
  // closes.
  const shape = Object.keys(snapshot()).sort().join(',');
  if (shape !== [...SNAPSHOT_FIELDS].sort().join(',')) {
    die(`SNAPSHOT_FIELDS no longer matches what snapshot() returns.\n`
      + `            snapshot():       ${shape}\n`
      + `            SNAPSHOT_FIELDS:  ${[...SNAPSHOT_FIELDS].sort().join(',')}\n`
      + '            That list is what a case row is allowed to assert, checked at load. Bring\n'
      + '            the two back into step in the same commit as the field that moved.');
  }
  const runScript = (target, keys, idleMs) => {
    setWords(Array.isArray(target) ? target : [target]);
    for (const k of keystrokes(keys)) press(k);
    // Thinking time, then re-read the stats the way the page does after every
    // keystroke. WPM is the only readout that moves without one.
    if (idleMs) { h.advanceClock(idleMs); page.updateStats(); }
    return snapshot();
  };
  // The text is what the KEYS made, replayed through practice.html's own
  // composeKeys(). Everything Backspace does rests on that invariant — undo pops
  // the log and re-composes — so a log that has drifted from the text would make
  // the Backspace rows above pass while undo did something else entirely.
  const checkKeystrokeLog = (id, got) => {
    const replayed = page.composeKeys([...page.state.keys]);
    const text = replayed.committed + replayed.buffer;
    if (text !== got.text) {
      failures.push(`${id}: the keystroke log ${JSON.stringify(got.keys)} replays to ${JSON.stringify(text)}, `
        + `but the display holds ${JSON.stringify(got.text)} — undo pops that log and re-composes it, `
        + 'so the two disagreeing means Backspace is undoing something the typist did not type');
    }
  };

  // --- every target, both printed spelling orders, must score 100% ----------
  // This is round 1's defect stated exhaustively, and it doubles as the "no
  // strands" sweep: at every state along a flawless run the next-key hint must
  // light SOMETHING. A state the scorer calls correct and the hint cannot leave
  // is a typist told they are fine with nowhere to go.
  let replays = 0, strands = 0, targets = 0, smears = 0;
  for (const [level, words] of Object.entries(page.WORD_LISTS)) {
    for (const word of words) {
      targets++;
      for (const [order, spell] of [['sớm', page.wordToTelex], ['muộn', page.wordToTelexLateTone]]) {
        const keys = spell(word);
        setWords([word]);
        replays++;
        let stranded = null, smeared = null;
        if (snapshot().hints === 0) stranded = '';
        for (const key of keystrokes(keys)) {
          press(key);
          const s = snapshot();
          if (!s.ended && s.hints === 0 && stranded === null) stranded = s.text;
          // A FLAWLESS run must paint nothing wrong at ANY intermediate state.
          // Every state here is one the scorer accepts, so a mark on any of them
          // is the display contradicting the readout — and the states this
          // catches are the half-typed ones no row names one by one.
          if (s.marked !== '' && smeared === null) smeared = s;
        }
        const got = snapshot();
        const want = { text: word, errors: 0, accuracy: 100, ended: true, border: 'match', notice: false };
        const bad = expectationProblems(`${level} "${word}" (dấu ${order}, '${keys}')`, got, want);
        if (bad.length) failures.push(...bad);
        if (stranded !== null) {
          strands++;
          failures.push(`STRANDED  ${level} "${word}" (dấu ${order}): the scorer accepts ${JSON.stringify(stranded)} `
            + 'but the next-key hint lights no key — correct, and nowhere to go');
        }
        if (smeared !== null) {
          smears++;
          failures.push(`SMEARED  ${level} "${word}" (dấu ${order}): a flawless run painted `
            + `${JSON.stringify(smeared.marked)} as wrong at ${JSON.stringify(smeared.text)} `
            + `(${JSON.stringify(smeared.paint)}) — nothing was mistyped, so nothing may be marked`);
        }
      }
    }
  }
  // The sweep's own anti-vacuity check, and a cross-check while it is here: the
  // two halves of the PASS line count the SAME word lists out of two independent
  // extractions of practice.html — the engine slice (checkWordLists) and the
  // whole script under the DOM stub. `replays === 0` alone could not tell an
  // empty WORD_LISTS from a sweep that had stopped iterating it.
  if (targets !== expectedTargets || replays !== 2 * targets) {
    die(`the 100%-run sweep saw ${targets} target(s) and made ${replays} replay(s); practice.html's\n`
      + `            WORD_LISTS holds ${expectedTargets} target(s), which is ${2 * expectedTargets} replays — both spelling\n`
      + '            orders for each, the two the hint prints.\n'
      + '            This sweep is the exhaustive form of round 1\'s defect (perfect typing\n'
      + '            scored 33%) and it is what the PASS line means by "N flawless replays".\n'
      + '            A sweep that iterates nothing still prints a number.');
  }

  // --- the constructed slip cases ------------------------------------------
  for (const c of SCORING_CASES) {
    const got = runScript(c.target, c.keys, c.idle);
    failures.push(...expectationProblems(c.id, got, c.expect));
    checkKeystrokeLog(c.id, got);
  }

  // --- keystrokes the engine swallows cost nothing and earn nothing ---------
  for (const c of NOOP_CASES) {
    setWords([c.target]);
    for (const key of keystrokes(c.prefix)) press(key);
    const before = snapshot();
    press(c.key);
    const after = snapshot();
    if (after.text !== before.text) {
      failures.push(`${c.id}: pressing "${c.key}" after '${c.prefix}' changed the text from `
        + `${JSON.stringify(before.text)} to ${JSON.stringify(after.text)} — this case is about a key the `
        + 'engine SWALLOWS, and that premise no longer holds, so it is testing nothing');
      continue;
    }
    for (const field of ['typed', 'errors', 'accuracy', 'wpm']) {
      if (after[field] !== before[field]) {
        failures.push(`${c.id}: a swallowed keystroke moved ${field} from ${JSON.stringify(before[field])} `
          + `to ${JSON.stringify(after[field])} — nothing was typed, so nothing may be counted`);
      }
    }
    if (before.wpm === WPM_UNMEASURED) {
      failures.push(`${c.id}: WPM still reads "${WPM_UNMEASURED}" after '${c.prefix}', so the WPM half of this `
        + 'case is vacuous — lengthen the prefix or raise KEY_INTERVAL_MS');
    }
  }

  // --- the same slip costs the same wherever it is typed --------------------
  for (const c of POSITION_CASES) {
    const early = runScript(c.target, c.early);
    const late = runScript(c.target, c.late);
    const off = early.errors !== late.errors
      || (c.symmetric && (early.typed !== late.typed || early.accuracy !== late.accuracy));
    if (off) {
      failures.push(`POSITION  ${c.id} on ${JSON.stringify(c.target)}: the same slip costs `
        + `${early.errors} error(s) of ${early.typed} (${early.accuracy}%) typed early but `
        + `${late.errors} of ${late.typed} (${late.accuracy}%) typed late.\n`
        + `              early '${c.early}' -> ${JSON.stringify(early.text)}\n`
        + `              late  '${c.late}' -> ${JSON.stringify(late.text)}\n`
        + '              One mistake is one mistake wherever it lands. A slip that changes a\n'
        + '              syllable\'s LENGTH is the one that used to cascade: units were paired\n'
        + '              by character index, so everything after it lost alignment and was\n'
        + '              charged again for the same slip.');
    }
    if (early.errors === 0) {
      failures.push(`POSITION  ${c.id}: '${c.early}' was charged nothing at all — the case is meant to`
        + ' contain a slip, so it is comparing two clean runs and proving nothing');
    }
  }

  // --- more mistakes must read worse ---------------------------------------
  for (const c of SEVERITY_CASES) {
    const one = runScript(c.target, c.one);
    const many = runScript(c.target, c.many);
    if (one.errors !== c.oneErrors || many.errors !== c.manyErrors) {
      failures.push(`SEVERITY  ${c.id}: charged ${one.errors} error(s) for the ${c.oneErrors}-slip run and `
        + `${many.errors} for the ${c.manyErrors}-slip run.\n`
        + '              Each slip is in a different SYLLABLE, and each is its own mistake:\n'
        + '              a rising edge taken on the whole text goes deaf after the first one,\n'
        + '              because a syllable the typist has left can never be repaired.');
    }
    if (!(many.accuracy < one.accuracy)) {
      failures.push(`SEVERITY  ${c.id}: the ${c.manyErrors}-slip run reads ${many.accuracy}% and the `
        + `${c.oneErrors}-slip run ${one.accuracy}% — the worse run must read worse.\n`
        + '              This is how the denominator used to HEAL a bad run: errorChars\n'
        + '              frozen while totalChars kept climbing.');
    }
  }

  // --- the accuracy pair, at every one of those states ----------------------
  for (const fault of h.statFaults) {
    failures.push(`STATS   ${fault}.\n`
      + '              accuracy = errorChars / unitAttempts, and BOTH count units — so every\n'
      + '              attempt is either broken or it is not and the readout cannot leave\n'
      + '              [0, 100]. That is the whole reason the denominator stopped counting\n'
      + '              keystrokes; while the two sides counted different things their ratio\n'
      + '              had no meaning. Deleting the `repaired` re-arm in recordKeystroke is\n'
      + '              the shortest way to break this — a syllable brought back to correct\n'
      + '              owes a second attempt, and without it a second wrong tone is charged\n'
      + '              against an attempt the first one already spent.');
  }

  // --- the border was READ, at every state every case above passed through ---
  // Reported once per distinct fault and last, because one missing class shows
  // up in hundreds of snapshots and the fix is one edit.
  for (const fault of h.borderFaults) {
    failures.push(`BORDER  ${fault}.\n`
      + `              Exactly one of ${BORDER_CLASSES.join(' / ')} says what the display is telling\n`
      + '              the typist: on target, off target but recoverable, or dead end. The\n'
      + '              cases below read that class rather than inferring it, so a class that\n'
      + '              stopped being painted is a fault here and not a silent default.\n'
      + '              If practice.html now says this a different way, teach snapshot() the\n'
      + '              new names in the same commit — do NOT let `border` fall back to one of\n'
      + '              the values the cases expect, which is exactly what made the\n'
      + '              partial-good rows decorative: the fallback WAS the expected value, so\n'
      + '              deleting the class from the app changed nothing here.');
  }

  // --- and so was the PAINT, at every one of those states -------------------
  // Same treatment, same reason, one level down: the characters were never read
  // by anything until now, so the whole paint could be deleted and this file
  // still printed PASS. Deduplicated and capped — one wrong rule marks tens of
  // thousands of states and the fix is one edit.
  const paintFaults = [...h.paintFaults];
  // The rationale once, on the first one: one wrong rule produces dozens of these
  // and the explanation is the same explanation every time.
  const PAINT_STAKES =
      '              The display\'s characters are READ out of its innerHTML and compared\n'
    + '              against the SCORER\'s own verdicts — practice.html\'s unitSteps(), the\n'
    + '              walk the paint is drawn from. A unit the scorer calls broken has to be\n'
    + '              visibly broken and a unit it calls fine has to be visibly fine; both\n'
    + '              directions have shipped (round 6 marked 29 of 31 characters at 98%,\n'
    + '              round 7 marked nothing at 0% behind a red border and a "press\n'
    + '              Backspace" notice).\n'
    + '              If practice.html now paints differently, teach PAINT_CODE the new\n'
    + '              palette entry in the same commit — the reader learns the MARKUP from\n'
    + '              the app, so re-tuning a colour is free, but a paint nothing asserts is\n'
    + '              a paint that can go wrong quietly.';
  paintFaults.slice(0, 6).forEach((fault, i) => {
    failures.push(`PAINT  ${fault}.` + (i === 0 ? `\n${PAINT_STAKES}` : ''));
  });
  if (paintFaults.length > 6) {
    failures.push(`PAINT  ... and ${paintFaults.length - 6} more distinct paint fault(s)`
      + (h.paintFaults.size >= PAINT_FAULT_LIMIT ? ` (collection stopped at ${PAINT_FAULT_LIMIT})` : ''));
  }
  // Anti-vacuity for the whole block above: a reader that never read anything
  // records no faults and reads exactly like a clean run.
  const paintStates = h.paintStates();
  if (paintStates < replays) {
    die(`the paint was read at ${paintStates} state(s) across ${replays} replays and every case —\n`
      + '            fewer than one per replay, so most of the run went unlooked-at.\n'
      + '            snapshot() reads the display\'s characters on every call; a number this low\n'
      + '            means the snapshots stopped happening, not that the app got simpler.');
  }

  return {
    failures,
    counts: {
      targets, replays, strands, smears, paintStates,
      cases: SCORING_CASES.length,
      noops: NOOP_CASES.length,
      positions: POSITION_CASES.length,
      severities: SEVERITY_CASES.length,
    },
  };
}

// ---------------------------------------------------------------------------
// telex-conformance.txt: `@section <name>`, `input<TAB>expected`, # comments,
// blank lines ignored.
// ---------------------------------------------------------------------------
function loadVectors() {
  const text = read(VECTOR_PATH, 'conformance vectors');
  // Group headers ("# --- ...") are kept as entries so the block generated for
  // practice.html stays as readable as the spec it comes from.
  const entries = [];
  let section = null;
  text.split(/\r?\n/).forEach((raw, i) => {
    const lineNo = i + 1;
    const trimmed = raw.trim();
    if (trimmed === '') return;
    if (trimmed.startsWith('@section')) {
      const name = trimmed.split(/\s+/)[1];
      if (!SECTIONS.includes(name)) {
        die(`${VECTOR_PATH}:${lineNo}: unknown section "${name}" (expected one of ${SECTIONS.join(', ')})`);
      }
      section = name;
      return;
    }
    if (trimmed.startsWith('#')) {
      const m = trimmed.match(/^#\s*---\s*(.*?)\s*$/);
      if (m) entries.push({ kind: 'group', section, text: m[1] });
      return;
    }
    const tab = raw.indexOf('\t');
    if (tab < 0) die(`${VECTOR_PATH}:${lineNo}: no TAB separator`);
    const input = raw.slice(0, tab);
    const expected = raw.slice(tab + 1).replace(/^\t+/, '').trimEnd();
    if (input === '') die(`${VECTOR_PATH}:${lineNo}: empty input`);
    if (section === null) {
      die(`${VECTOR_PATH}:${lineNo}: vector before any "@section" line — say how it is driven`);
    }
    // The transform section feeds transform() directly, which has no notion of a
    // syllable ending; a non-letter there would silently test nothing real.
    if (section === 'transform' && !/^[A-Za-z]+$/.test(input)) {
      die(`${VECTOR_PATH}:${lineNo}: "${input}" has a non-letter — it belongs in @section integration`);
    }
    // A syllable-ending character here would commit, and an IME cannot reach
    // back across a commit — the vector would then be asking the engine for
    // something it deliberately declines to do, and would fail for a reason
    // that says nothing about Backspace.
    if (section === 'backspace' && !new RegExp(`^[A-Za-z${VECTOR_BACKSPACE}]+$`).test(input)) {
      die(`${VECTOR_PATH}:${lineNo}: "${input}" — @section backspace takes letters and `
        + `${VECTOR_BACKSPACE} only. A syllable-ending character belongs in @section integration.`);
    }
    entries.push({ kind: 'vector', section, lineNo, input, expected });
  });
  const vectors = entries.filter(e => e.kind === 'vector');
  if (vectors.length === 0) die(`${VECTOR_PATH}: no vectors found`);
  for (const s of SECTIONS) {
    if (!vectors.some(v => v.section === s)) die(`${VECTOR_PATH}: section "${s}" has no vectors`);
  }
  return { entries, vectors };
}

function codePoints(s) {
  return [...s].map(c => 'U+' + c.codePointAt(0).toString(16).toUpperCase().padStart(4, '0')).join(' ');
}

// ---------------------------------------------------------------------------
// The vector block embedded in practice.html — generated, never hand-written.
// Only the transform section goes in: the page's runSelfTests() replays each
// entry through bare transform(), which is exactly what that section means. The
// integration section needs the apply path and is checked here instead.
// ---------------------------------------------------------------------------
function jsString(s) {
  return `'${s.replace(/\\/g, '\\\\').replace(/'/g, "\\'")}'`;
}

function buildVectorBlock(entries) {
  const mine = entries.filter(e => e.section === 'transform');
  const width = Math.max(...mine
    .filter(e => e.kind === 'vector')
    .map(e => jsString(e.input).length + 1));
  const rows = [];
  let prevKind = null;
  for (const e of mine) {
    if (e.kind === 'group') {
      if (prevKind === 'vector') rows.push('');
      rows.push(`  // ${e.text}`);
    } else {
      rows.push(`  [${(jsString(e.input) + ',').padEnd(width + 1)}${jsString(e.expected)}],`);
    }
    prevKind = e.kind;
  }
  return [
    GEN_BEGIN,
    '// Section "transform" of the spec only — runSelfTests() replays these through',
    '// bare transform(). The spec\'s "integration" section drives the apply path and',
    '// is checked by check-parity.mjs, which runs both sections through both engines.',
    'const TELEX_VECTORS = [',
    ...rows,
    '];',
    GEN_END,
  ].join('\n');
}

// The embedded block and the block the spec asks for, line by line. "Out of
// sync" is not a diagnosis: an innocuous regeneration and someone quietly
// hand-editing a vector inside practice.html produce the identical message, and
// the prescribed --sync-selftests silently overwrites whichever it was. Both
// texts are in memory, so show the difference before advising the fix.
// Compared per VECTOR, not per line: inserting a group high up shifts every line
// below it, and a line diff would then report hundreds of differences and bury
// the one that matters. The rows are `['input', 'expected'],` — the same shape
// buildVectorBlock() writes.
function blockRows(text) {
  const unq = (s) => s.replace(/\\(['\\])/g, '$1');
  const rows = [];
  const re = /^\s*\['((?:[^'\\]|\\.)*)',\s*'((?:[^'\\]|\\.)*)'\],[ \t]*$/gm;
  let m;
  while ((m = re.exec(text))) rows.push([unq(m[1]), unq(m[2])]);
  return rows;
}

function blockDiff(embedded, wanted) {
  const A = blockRows(embedded), B = blockRows(wanted);
  const key = ([i, e]) => `${i}\t${e}`;
  const count = (rows) => rows.reduce((m, r) => m.set(key(r), (m.get(key(r)) || 0) + 1), new Map());
  const cb = count(B), ca = count(A);
  const removed = A.filter(r => { const k = key(r); const n = cb.get(k) || 0; if (n) { cb.set(k, n - 1); return false; } return true; });
  const added = B.filter(r => { const k = key(r); const n = ca.get(k) || 0; if (n) { ca.set(k, n - 1); return false; } return true; });
  // A row whose input survives but whose expectation moved is the interesting
  // case — that is a changed answer, not an added or a deleted vector.
  const changed = [];
  for (let i = removed.length - 1; i >= 0; i--) {
    const j = added.findIndex(r => r[0] === removed[i][0]);
    if (j < 0) continue;
    changed.push({ input: removed[i][0], embedded: removed[i][1], wanted: added[j][1] });
    added.splice(j, 1);
    removed.splice(i, 1);
  }
  // Everything that is not a row: the generated comments.
  const comments = (t) => t.split('\n').filter(l => !/^\s*\[/.test(l)).map(l => l.trim()).join('\n');
  return { changed: changed.reverse(), added, removed, commentsDiffer: comments(embedded) !== comments(wanted) };
}

function printBlockDiff(diff, log, limit = 8) {
  const show = (rows, render) => {
    for (const r of rows.slice(0, limit)) log(`        ${render(r)}`);
    if (rows.length > limit) log(`        ... and ${rows.length - limit} more`);
  };
  if (diff.changed.length) {
    log(`      ${diff.changed.length} vector(s) ANSWER DIFFERENTLY:`);
    show(diff.changed, r => `${JSON.stringify(r.input).padEnd(14)} embedded ${JSON.stringify(r.embedded).padEnd(12)} spec ${JSON.stringify(r.wanted)}`);
  }
  if (diff.added.length) {
    log(`      ${diff.added.length} vector(s) in the spec but NOT embedded:`);
    show(diff.added, ([i, e]) => `+ ${JSON.stringify(i).padEnd(14)} -> ${JSON.stringify(e)}`);
  }
  if (diff.removed.length) {
    log(`      ${diff.removed.length} vector(s) embedded but NOT in the spec:`);
    show(diff.removed, ([i, e]) => `- ${JSON.stringify(i).padEnd(14)} -> ${JSON.stringify(e)}`);
  }
  if (!diff.changed.length && !diff.added.length && !diff.removed.length) {
    log('      every vector matches; only the generated comments differ.');
  } else if (diff.commentsDiffer) {
    log('      (the generated comments differ too)');
  }
}

