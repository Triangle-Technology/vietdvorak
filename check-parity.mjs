#!/usr/bin/env node
// ============================================================================
// check-parity.mjs — drift alarm for the two Telex implementations
// ============================================================================
// VietDvorak ships the same Telex engine twice: once in AHK v2 (VietDvorak.ahk,
// the actual input method) and once in JS (practice.html, the trainer). The two
// runtimes cannot share code, so the SPEC is what is shared instead:
// telex-conformance.txt is the single source of truth for observable behaviour.
//
// ONE command checks BOTH engines. Every vector runs through the JS engine
// extracted live from practice.html AND through VietDvorak.ahk's own
// Transform(), sliced verbatim out of the shipped file and executed under
// AutoHotkey. Any disagreement with the spec — or between the two engines — is
// listed and exits non-zero. Run it after ANY change to either engine:
//
// Four things beyond the vectors are checked here, because no vector can reach
// them and this is the command people actually run:
//   - the SYLLABLE-BREAK RULE, swept out of VietDvorak.ahk key by key and
//     compared against practice.html's isResetChar(), plus the keep-alive codes
//     no character can type (EXPECTED_KEEPALIVE / DENIED_KEEPALIVE);
//   - the REGISTRATION BLOCK that installs that rule, read as text because
//     executing it would create a real keyboard hook (assertRegistration);
//   - the trainer's WORD LISTS, replayed through the engine to prove every
//     target is still typeable (checkWordLists — practice.html owns the guard,
//     this runs it);
//   - the trainer's SCORING LAYER, driven through practice.html's real keydown
//     handler under a DOM stub (checkScoring). The engine has 266 vectors and a
//     two-engine drift alarm; the layer that decides whether a keystroke was
//     RIGHT had nothing at all, and four of the last five defects lived there.
//     Every one of those five is a case in SCORING_CASES / POSITION_CASES now.
//     What the typist SEES is part of that layer and is read the same way: the
//     painted characters come out of the display's own innerHTML (see the paint
//     reader), so "the readout says 0% and every character on screen is green"
//     is a failure here rather than a thing only a human ever notices.
//
//     node check-parity.mjs                  check all engines + embedded vectors
//     node check-parity.mjs --sync-selftests regenerate the embedded vector block
//     node check-parity.mjs --skip-ahk       skip AHK;  PARTIAL, and STILL exits 1
//     node check-parity.mjs --skip-rust      skip Rust; PARTIAL, and STILL exits 1
//
// --skip-ahk does not buy a green exit, deliberately: the exit code is the only
// thing CI reads, and a JS-only run has not executed the shipped input method at
// all. A human iterating on practice.html from a non-Windows box wants the JS
// verdict without the AutoHotkey search and its wall of paths — that is what the
// flag is for. A pipeline that genuinely wants to proceed anyway has to write
// `|| true` at the call site, where the decision is visible in the diff.
//
// A THIRD ENGINE, as of the Rust port: crates/vietdvorak-core, driven through
// the vdconform binary over the same section<TAB>input protocol the AHK harness
// already uses. It is deliberately NOT a `cargo test` that reads this spec for
// itself — that would be a second parser and a second verdict for one spec, and
// the two would drift. vdconform computes and prints; this file alone judges.
// One harness, one exit code, three engines.
//
// --skip-rust carries exactly the same terms as --skip-ahk, for the same reason.
// It exists for the machine that has no Rust toolchain, not for a red run.
//
// No dependencies, no network, no arguments needed. Node 14+.
//
// practice.html also embeds the vectors, because it must work offline from a
// file:// URL and cannot fetch the .txt. That embedded block is generated by
// --sync-selftests and its freshness is checked on every plain run, so the copy
// can never drift away from the spec unnoticed.
//
// WHY THE AHK SIDE IS SLICED RATHER THAN COPIED: a copy is one more thing to
// drift, which is the exact failure this script exists to catch. The harness is
// generated into a temp directory from the shipped .ahk on every run, between
// two markers that are section banners in that file — never line numbers, which
// go stale silently. It contains the real Transform() and the real syllable-
// break table, plus a file-in/file-out runner, and NOTHING that registers a
// hotkey (asserted below before AutoHotkey is ever invoked).
// ============================================================================

