// the functions whose absence made this whole layer untested, and the PASS line
// below claims they were exercised.
const PAGE_EXPORTS = [
  'state', 'els', 'unitStatuses', 'canStillFinish', 'isRepairable',
  'recordKeystroke', 'updateStats', 'setStuckNotice', 'applyKey', 'transform',
  'resetTelexState', 'isResetChar', 'WORD_LISTS', 'wordToTelex', 'wordToTelexLateTone',
  'loadCurrentWord', 'getCurrentText', 'isComposingToward', 'STUCK_NOTICE',
  // The paint and the walk it is drawn from. `unitSteps` is here so the marked
  // set can be compared against the SCORER's verdicts rather than against a
  // second opinion computed here — see paintFaults in snapshot().
  'PAINT', 'unitSteps', 'UNIT_OK', 'UNIT_WRONG', 'UNIT_STUCK', 'composeKeys',
];

// `typeof` rather than a bare reference: a name that no longer exists has to
// arrive here as `undefined` and be REPORTED, not blow up inside the evaluator
// as a ReferenceError that reads like the page is broken.
const pageReturnExpr = (names) =>
  names.map(n => `${n}: (typeof ${n} === 'undefined' ? undefined : ${n})`).join(', ');

// Milliseconds between synthetic keystrokes. Fixed, and injected as the page's
// Date: WPM is a rate, and a rate read off the wall clock is a flaky test.
// 250 ms clears WPM_MIN_ELAPSED_MS inside a normal word, so the WPM readout the
// cases assert on is a real number and not the placeholder.
//
// It is also what makes WPM ASSERTABLE, which it was not: the cases carried the
// number along and compared it to nothing, so a documented off-by-one and a
// doubled formula both passed. The typing model here is fully known — the first
// keystroke marks t=0 and does not happen inside the measured window — so for a
// script of P presses of which C were counted:
//
//     elapsed = KEY_INTERVAL_MS x (P - 1)      characters measured = C - 1
//     WPM     = ((C - 1) / 5) / (elapsed / 60000)   =  48 x (C - 1) / (P - 1)
//
// i.e. 250 ms/key is 4 keys/s is 48 WPM at the standard 5 characters per word,
// whenever every press counted. The rows that pin it are the wpm-* cases below;
// each writes its own arithmetic out, because a number nobody can re-derive is a
// number the next maintainer will "fix" by pasting in whatever the code prints.
const KEY_INTERVAL_MS = 250;
const WPM_STEADY = 48;    // the rate above, for a script where C === P

// The three classes practice.html paints on #input-display, and the only three
// values a case may expect for `border`. Exactly one of them must be on the
// element at every moment a case looks — see snapshot(), which records anything
// else as a fault instead of defaulting to one of them.
const BORDER_CLASSES = ['match', 'partial-good', 'bad'];
const BORDER_UNPAINTED = '<no border class>';

// ---------------------------------------------------------------------------
// THE PAINT — read off the display's own innerHTML
// ---------------------------------------------------------------------------
// The border says one thing about the whole box. The CHARACTERS say what is
// wrong and what the typist can still do about it, and until this block nothing
// executable had ever looked at one: snapshot() read the border class, the stuck
// notice and the next-hint count, so DELETING the paint rewrite outright still
// printed PASS. That is the same gap, one level down, that let four consecutive
// rounds ship a defect in the layer above.
//
// Two rules keep this reader honest, and they are the two the border guard
// learned the hard way:
//
//   IT LEARNS THE MARKUP FROM THE APP. The style string of every paint is taken
//   from practice.html's own PAINT palette, by CALLING each entry — so re-tuning
//   a colour is not a failure here, while a span this file cannot account for
//   is. A hard-coded copy of the palette would be a second source of truth for
//   the exact thing being asserted.
//
//   IT NEVER FALLS BACK. A span whose markup is not in the palette, or markup
//   left over after the spans are consumed, is recorded as a FAULT. An expected
//   value that is also the reader's own default cannot fail — that is precisely
//   what made the partial-good border rows decorative for four rounds.
//
// One letter per paint, so a whole state's worth of them is one short assertable
// string. The three-way distinction the app now makes is the middle three:
// `p` is a mark still on its way, `a` is a mark that is WRONG but one keystroke
// from home, `w` is a mark that is wrong and unreachable. Painting all three the
// same is what let a red border, a "press Backspace" notice and a charged error
// sit over a line of green.
const PAINT_CODE = {
  right: 'r',       // typed, and exactly the character the target has there
  pending: 'p',     // typed, right letter, mark not there YET — in a unit that can still finish
  repairable: 'a',  // typed and WRONG, one keystroke from home (a wrong tone) — amber
  wrong: 'w',       // typed, wrong, and no keystroke takes it back
  surplus: 's',     // typed past the end of the target span its unit was paired with
  missing: 'm',     // NOT typed and no longer typeable — the hole, shown in the target's own character
  owed: 'o',        // not typed yet, still ahead of the caret
};
// Which paints are a character the TYPIST put there (the rest are the target's
// own characters, printed for a hole or for the tail still to be typed), and
// which of them MARK the character as wrong. `pending` is deliberately not a
// mark: the whole point of the three-way split is that it is not one.
const PAINT_TYPED = new Set(['right', 'pending', 'repairable', 'wrong', 'surplus']);
const PAINT_MARKS = new Set(['repairable', 'wrong', 'surplus', 'missing']);

// The spans practice.html emits, and the only shapes this reader accepts:
// one styled span per painted character, plus the cursor and the placeholder.
const SPAN_RE = /<span (?:style="([^"]*)"|class="([^"]*)")>([^<]*)<\/span>/g;
const HTML_ENTITY = { '&amp;': '&', '&lt;': '<', '&gt;': '>', '&quot;': '"', '&#39;': "'" };
const unescapeHtml = (s) => s.replace(/&amp;|&lt;|&gt;|&quot;|&#39;/g, (m) => HTML_ENTITY[m]);

// practice.html's palette -> { style string -> paint name }. Every check that
// this file and the page still agree about what a paint IS happens here, once,
// at load: a palette entry with no code, a code with no palette entry, a paint
// with no style, and — the one the three-way distinction rests on — two paints
// that render identically, which would make them indistinguishable on screen
// and unassertable here.
function paintStyleTable(PAINT) {
  const names = Object.keys(PAINT || {});
  if (names.length === 0) die('practice.html\'s PAINT palette is empty — there is nothing painting the typed text.');
  const unknown = names.filter(n => !(n in PAINT_CODE));
  if (unknown.length) {
    die(`practice.html's PAINT palette has ${unknown.length} entry this file does not know: ${unknown.join(', ')}.\n`
      + '            A new paint is a new thing the display can SAY to the typist, so it needs a\n'
      + '            letter in PAINT_CODE and a row that pins when it appears. Adding one without\n'
      + '            that is how a paint nobody asserts gets shipped.');
  }
  const gone = Object.keys(PAINT_CODE).filter(n => !names.includes(n));
  if (gone.length) {
    die(`practice.html's PAINT palette no longer has: ${gone.join(', ')}.\n`
      + '            The rows below assert those paints by name. If the palette really has lost\n'
      + '            one, say so here in the same commit and delete the rows that pinned it —\n'
      + '            do not let this file go on claiming to read a distinction the app dropped.');
  }
  const byStyle = new Map();
  for (const name of names) {
    let markup;
    try { markup = String(PAINT[name]('')); } catch (err) {
      die(`practice.html's PAINT.${name} could not be called to learn its markup: ${err.message}`);
    }
    const m = /style="([^"]*)"/.exec(markup);
    if (!m) die(`practice.html's PAINT.${name} paints no style attribute (${JSON.stringify(markup)}) — this reader\n`
      + '            identifies a paint BY its style, so it could not tell that one apart.');
    if (byStyle.has(m[1])) {
      die(`practice.html paints ${name} and ${byStyle.get(m[1])} identically: ${m[1]}\n`
        + '            Those two are DIFFERENT things to the typist — a mark still on its way, a\n'
        + '            mark that is wrong but repairable, a mark that is dead — and two of them\n'
        + '            drawn the same way cannot be told apart on screen either. Every assertion\n'
        + '            below that separates them would silently become one assertion.');
    }
    byStyle.set(m[1], name);
  }
  return byStyle;
}

// innerHTML -> [{ ch, paint }], or a problem string. Nothing is inferred: a span
// this reader cannot name, or a tail it cannot consume, comes back as a fault.
function readPaint(innerHTML, byStyle) {
  const out = [];
  let placeholder = null;
  SPAN_RE.lastIndex = 0;
  let m, consumed = 0;
  while ((m = SPAN_RE.exec(innerHTML)) !== null) {
    if (m.index !== consumed) {
      return { problem: `#input-display has markup between its spans: ${JSON.stringify(innerHTML.slice(consumed, m.index))}` };
    }
    consumed = SPAN_RE.lastIndex;
    if (m[2] !== undefined) {
      if (m[2] === 'cursor') continue;
      if (m[2] === 'placeholder') { placeholder = unescapeHtml(m[3]); continue; }
      return { problem: `#input-display carries an unknown span class ${JSON.stringify(m[2])}` };
    }
    const paint = byStyle.get(m[1]);
    if (!paint) return { problem: `#input-display carries a span this file cannot name: style ${JSON.stringify(m[1])}` };
    for (const ch of unescapeHtml(m[3])) out.push({ ch, paint });
  }
  if (consumed !== innerHTML.length) {
    return { problem: `#input-display has markup after its last span: ${JSON.stringify(innerHTML.slice(consumed))}` };
  }
  return { chars: out, placeholder };
}

// A fault set is a diagnosis, not a log: one wrong rule paints tens of thousands
// of states wrong, and the maintainer needs the first few and the count.
const PAINT_FAULT_LIMIT = 200;
const addFault = (faults, msg) => { if (faults.size < PAINT_FAULT_LIMIT) faults.add(msg); };

// ONE state's paint, checked against the SCORER'S OWN verdicts — page.unitSteps,
// the same walk updatePracticeDisplay() paints from and recordKeystroke() charges
// from. Nothing here re-derives what SHOULD be marked; it asks the scorer and
// compares. That is the whole point: the defect these invariants exist to catch
// is the paint and the score DISAGREEING, and a check with its own opinion about
// which units are broken would just be a third opinion to disagree with.
//
// Both directions are pinned, because both have shipped:
//   OVER-MARKED   a unit the scorer calls fine, painted wrong. Round 6: after a
//                 stray letter at the front of a sentence, 29 of 31 characters
//                 were red while the readout said 98%.
//   UNDER-MARKED  a unit the scorer CHARGED AN ERROR FOR, painted with nothing
//                 wrong at all. Round 7: "nă " for "năm " types every character
//                 correctly and is still broken — red border, "press Backspace",
//                 0%, and a line of green.
function paintOf(text, target, page, byStyle, faults) {
  const read = readPaint(page.els.display.innerHTML, byStyle);
  const where = `typed ${JSON.stringify(text)} toward ${JSON.stringify(target)}`;
  // Unreadable markup: there is nothing to hand a row, and the fault says why.
  // Every other path below returns what was ACTUALLY painted, fault or no fault,
  // so a row always sees the app's own answer rather than a blank this file made
  // up — the reader never falls back, and that includes falling back to nothing.
  if (read.problem) { addFault(faults, `${read.problem}  (${where})`); return { code: '', marked: '', hard: '' }; }
  const chars = read.chars;
  const code = chars.map(e => PAINT_CODE[e.paint]).join('');
  const marked = chars.filter(e => PAINT_MARKS.has(e.paint)).map(e => e.ch).join('');
  // The marks no keystroke can take back — the character-level half of what makes
  // the border red. `repairable` is deliberately not one of them.
  const hard = chars.filter(e => PAINT_MARKS.has(e.paint) && e.paint !== 'repairable')
    .map(e => e.ch).join('');

  if (text.length === 0) {
    // Nothing typed: the target itself, as a placeholder. It is READ, so a page
    // that stopped showing what to type is a fault and not a blank the reader
    // silently accepts.
    if (chars.length) {
      addFault(faults, `nothing has been typed, yet ${chars.length} character(s) are painted (${JSON.stringify(code)})`);
    } else if (read.placeholder !== target) {
      addFault(faults, `with nothing typed the display shows ${JSON.stringify(read.placeholder)} `
        + `instead of the target ${JSON.stringify(target)}`);
    }
    return { code, marked, hard };
  }

  // The typed characters shown ARE the typed text. This is what a deleted or
  // half-written paint loop fails first, and it has to be checked before the
  // marks are attributed to units: attribution walks the two in step.
  const shown = chars.filter(e => PAINT_TYPED.has(e.paint)).map(e => e.ch).join('');
  if (shown !== text) {
    addFault(faults, `the display paints ${JSON.stringify(shown)} where the typist typed ${JSON.stringify(text)}`);
    return { code, marked, hard };
  }

  const steps = page.unitSteps(text, target, true);
  // Which step each painted character belongs to, using ONLY the layout fact that
  // a step prints its typed characters and then its shortfall. No rule about
  // WHICH paint belongs where is restated here.
  const stepMarked = steps.map(() => false);
  let k = 0, broke = null;
  for (let s = 0; s < steps.length && broke === null; s++) {
    for (const want of [...steps[s].typed.join('')]) {
      const e = chars[k];
      if (!e || !PAINT_TYPED.has(e.paint)) {
        broke = `the display runs out of typed characters inside unit ${s + 1} (painted ${JSON.stringify(code)})`;
        break;
      }
      if (e.ch !== want) {
        broke = `unit ${s + 1} paints ${JSON.stringify(e.ch)} where the text has ${JSON.stringify(want)}`;
        break;
      }
      if (PAINT_MARKS.has(e.paint)) stepMarked[s] = true;
      k++;
    }
    while (broke === null && k < chars.length && !PAINT_TYPED.has(chars[k].paint)) {
      if (PAINT_MARKS.has(chars[k].paint)) stepMarked[s] = true;
      k++;
    }
  }
  if (broke !== null) { addFault(faults, `${broke}  (${where})`); return { code, marked, hard }; }

  steps.forEach((step, s) => {
    const unit = `unit ${s + 1} ${JSON.stringify(step.typed.join(''))} against ${JSON.stringify(step.want.join(''))}`;
    if (step.status !== page.UNIT_OK && !stepMarked[s]) {
      addFault(faults, `UNDER-MARKED  the scorer calls ${unit} ${step.status}, and the display marks nothing `
        + `in it: ${JSON.stringify(code)}  (${where})`);
    }
    if (step.status === page.UNIT_OK && stepMarked[s]) {
      addFault(faults, `OVER-MARKED  the scorer calls ${unit} ${page.UNIT_OK}, and the display marks something `
        + `in it: ${JSON.stringify(code)}  (${where})`);
    }
  });
  return { code, marked, hard };
}

function loadPracticePage(html) {
  const src = practiceScript(html);
  const doc = makeDom();
  // Fake timers, never fired: the auto-advance timeout belongs to the browser's
  // idle time, and a case that wants the next word says so by typing. Holding
  // them here (rather than letting Node's real timers run between cases) is what
  // keeps one case from advancing another case's word.
  const timers = new Map();
  let seq = 0;
  const setTimeoutStub = (fn) => { timers.set(++seq, fn); return seq; };
  const clearTimeoutStub = (h) => { timers.delete(h); };
  let clock = 1e6;
  const logs = [];
  const consoleStub = {
    log: (...a) => logs.push({ level: 'log', text: a.join(' ') }),
    error: (...a) => logs.push({ level: 'error', text: a.join(' ') }),
    warn: (...a) => logs.push({ level: 'warn', text: a.join(' ') }),
  };
  let page;
  try {
    // eslint-disable-next-line no-new-func
    page = new Function('document', 'window', 'setTimeout', 'clearTimeout', 'console', 'Date', 'navigator',
      `${src}\nreturn { ${pageReturnExpr(PAGE_EXPORTS)}, __wordEnded: () => wordEnded };`)(
      doc, { addEventListener() {} }, setTimeoutStub, clearTimeoutStub, consoleStub,
      { now: () => clock }, {});
  } catch (err) {
    die(`practice.html's script failed to evaluate under the DOM stub: ${err.message}\n`
      + '            The stub implements only the DOM the page used to use. A new API is a\n'
      + '            one-line addition to makeDom() — but check WHAT the page now needs\n'
      + '            first: the scoring cases are worth nothing if the page they drive is\n'
      + '            not the page that ships.');
  }
  for (const name of PAGE_EXPORTS) {
    if (page[name] === undefined) die(`practice.html no longer defines ${name} — the scoring harness drives it`);
  }
  const display = doc.getElementById('input-display');
  const handlers = display.listeners.get('keydown') || [];
  if (handlers.length !== 1) {
    die(`practice.html registered ${handlers.length} keydown handler(s) on #input-display; the scoring\n`
      + '            harness drives exactly one.\n'
      + '            Zero means the slice yielded no handler and every scoring case below\n'
      + '            would pass by doing nothing — which is the result this guard exists to\n'
      + '            refuse. More than one means it is no longer obvious which one scores.');
  }
  // The page runs its own self-test at the bottom of the script. It just ran,
  // into the captured console: a failure there is a failure here.
  const complained = logs.filter(l => l.level === 'error');
  if (complained.length) {
    die('practice.html\'s own runSelfTests() reported failures while loading:\n'
      + complained.slice(0, 6).map(l => `              ${l.text}`).join('\n'));
  }
  const keydown = handlers[0];

  const press = (key) => {
    clock += KEY_INTERVAL_MS;
    keydown({ key, ctrlKey: false, altKey: false, metaKey: false, preventDefault() {} });
  };
  // Put the page on a chosen word with the stats zeroed. Everything here goes
  // through the page's own loadCurrentWord(), so the cases start from the state
  // a real word change produces — latch cleared, timer cancelled, hint painted.
  const setWords = (words) => {
    page.state.mode = 'practice';
    page.state.words = [...words];
    page.state.wordIdx = 0;
    page.loadCurrentWord();
    page.state.startTime = null;
    page.state.totalChars = 0;
    page.state.errorChars = 0;
    page.state.unitAttempts = 0;
    page.resetTelexState();
    page.updateStats();
  };
  // Every border reading that was not exactly one class, deduplicated. Collected
  // here rather than asserted at each call site so that EVERY snapshot is
  // covered — including the several hundred taken inside the flawless-run sweep,
  // which no case names one by one.
  const borderFaults = new Set();
  // The one property the whole accuracy design rests on, checked WHEREVER the
  // stats are read rather than in a row that has to remember to ask. Both sides
  // count units, so every attempt is either broken or it is not: errors <=
  // attempts, and the percentage cannot leave [0, 100]. A row-based assertion
  // could not carry this — the hole it closes was found by deleting the `repaired`
  // re-arm in recordKeystroke, which sends the readout to -200% while every
  // existing row still passes, because no row typed a repair-then-rebreak
  // sequence and none pinned the pair on an error path.
  const statFaults = new Set();
  // The same treatment for the paint, and for the same reason: the invariants
  // below hold at EVERY state, not only at the states a row happens to name, and
  // the sweep walks tens of thousands of them. Deduplicated, because one wrong
  // rule paints thousands of states wrong and the fix is one edit.
  const paintFaults = new Set();
  const byStyle = paintStyleTable(page.PAINT);
  let paintStates = 0;
  const snapshot = () => {
    const cls = page.els.display.classList;
    // The border is READ off the element, and every reading that is not exactly
    // one of the three classes is a fault recorded here rather than smoothed
    // over. It used to be `match ? : bad ? : 'partial-good'` — a two-branch
    // ternary whose FALLBACK was 'partial-good', which is also the value the
    // partial-good rows expect. Deleting that class from practice.html outright
    // therefore changed nothing here: an assertion whose expected value is also
    // its own default cannot fail, and those rows were decorative.
    const painted = BORDER_CLASSES.filter(c => cls.contains(c));
    if (painted.length !== 1) {
      borderFaults.add(painted.length === 0
        ? `#input-display carries none of ${BORDER_CLASSES.join(' / ')} (className ${JSON.stringify(page.els.display.className)})`
        : `#input-display carries ${painted.length} of them at once: ${painted.join(' + ')}`);
    }
    const text = page.state.committed + page.state.buffer;
    const target = page.state.words[page.state.wordIdx] || '';
    const notice = page.els.feedback.textContent === page.STUCK_NOTICE;
    // errors <= attempts, and the readout in [0, 100]. Read here so every state
    // any case passes through is covered, including the several thousand no row
    // names one by one.
    const att = page.state.unitAttempts, err = page.state.errorChars;
    const acc = Number(page.els.acc.textContent);
    if (!Number.isFinite(att) || !Number.isFinite(err) || att < 0 || err < 0) {
      statFaults.add(`unitAttempts=${att} errorChars=${err} — a counter is negative or not a number`);
    } else if (err > att) {
      statFaults.add(`errorChars ${err} exceeds unitAttempts ${att} after ${JSON.stringify(text)}`
        + ` toward ${JSON.stringify(target)} — more units were broken than were ever attempted,`
        + ' so the two sides have stopped counting the same thing');
    }
    if (!Number.isFinite(acc) || acc < 0 || acc > 100) {
      statFaults.add(`the accuracy readout is ${JSON.stringify(page.els.acc.textContent)}`
        + ` after ${JSON.stringify(text)} toward ${JSON.stringify(target)} — outside [0, 100]`);
    }
    const painting = paintOf(text, target, page, byStyle, paintFaults);
    paintStates++;
    // THE CONTRADICTION THAT SHIPPED, stated in its own words rather than left to
    // follow from the unit-by-unit check above. The box is red, the notice says
    // press Backspace, an error has been charged — and every character on the
    // screen is drawn as if it were fine. Whatever the walk says, that state must
    // not exist: it is the app telling the typist two opposite things at once.
    if (painted.includes('bad') && painting.hard === '' && text.length > 0) {
      addFault(paintFaults, `the border is red${notice ? ' and the notice is up' : ''}, `
        + `yet nothing on screen is painted unrecoverable: ${JSON.stringify(painting.code)} `
        + `(typed ${JSON.stringify(text)} toward ${JSON.stringify(target)})`);
    }
    return {
      text,
      // The keystroke LOG that made the text. Backspace undoes one entry of this
      // list, which is why the two are separate readings: a row that pins only
      // the text cannot tell "undid one keystroke" from "undid one character",
      // and those differ by a whole keystroke exactly when a tone or a diacritic
      // is involved — i.e. on everything this app teaches.
      keys: page.state.keys.join(''),
      // `typed` is CHARACTERS PRODUCED — the counter WPM divides by elapsed time.
      // It is NOT the accuracy denominator. Accuracy is errors/attempts, both of
      // which count UNITS, and a row that wants to pin accuracy must say
      // `attempts` and `errors`. Conflating the two is the defect this pair was
      // split to end: while the numerator counted units and the denominator
      // counted keystrokes, their ratio decided a slip's final score by how much
      // typing happened to be left inside the damaged syllable.
      typed: page.state.totalChars,
      attempts: page.state.unitAttempts,
      errors: page.state.errorChars,
      accuracy: Number(page.els.acc.textContent),
      wpm: page.els.wpm.textContent,
      wordIdx: page.state.wordIdx,
      ended: page.__wordEnded(),
      border: painted.length === 1 ? painted[0]
        : painted.length === 0 ? BORDER_UNPAINTED : `<${painted.join('+')}>`,
      notice,
      hints: doc.querySelectorAll('.kb-key.next-hint').length,
      // One letter per painted character, in display order — see PAINT_CODE.
      // The typed characters and the target's own (a hole, or the tail still
      // owed) are in the SAME string because that is how the typist reads it.
      paint: painting.code,
      // Just the characters carrying a mark, so a row can say "exactly this much
      // is called wrong on screen" without spelling out the whole line.
      marked: painting.marked,
    };
  };
  // Thinking time. The clock is injected, so "the typist paused" is a fact this
  // harness can state exactly — and it is the only way to show that WPM is a RATE
  // rather than a per-keystroke constant, since a script where every press counts
  // reads WPM_STEADY whatever its length.
  const advanceClock = (ms) => { clock += ms; };
  return {
    page, doc, press, setWords, snapshot, advanceClock, borderFaults, paintFaults, statFaults,
    paintStates: () => paintStates,
  };
}

