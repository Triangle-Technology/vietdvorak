function lineStartOf(src, idx) {
  return src.lastIndexOf('\n', idx - 1) + 1;
}

function sliceAhkEngine(src) {
  const b = src.indexOf(AHK_ENGINE_BANNER);
  if (b < 0) die(`banner "${AHK_ENGINE_BANNER}" not found in VietDvorak.ahk — the slice markers are stale`);
  const rest = src.slice(lineStartOf(src, b));
  const decl = AHK_ENGINE_LAST_FN.exec(rest);
  if (!decl) die('Transform() declaration not found after the engine banner in VietDvorak.ahk');
  const afterDecl = decl.index + decl[0].length;
  const close = /^\}[ \t]*$/m.exec(rest.slice(afterDecl));
  if (!close) die('no column-0 "}" closing Transform() in VietDvorak.ahk');
  return rest.slice(0, afterDecl + close.index + close[0].length);
}

// Every `NAME := <number>` in the slice, so a keep-alive map written with named
// constants (`VK_LSHIFT, true`) reads the same as one written with raw codes.
// The Map literal's own rows have no `:=` and cannot match.
function sliceConstants(text) {
  const consts = new Map();
  const re = /^[ \t]*([A-Za-z_]\w*)[ \t]*:=[ \t]*(0[xX][0-9a-fA-F]+|\d+)[ \t]*(?:;.*)?$/gm;
  let m;
  while ((m = re.exec(text))) consts.set(m[1], Number(m[2]));
  return consts;
}

// The same, for STRING constants — because the hotkey guard below tests the text
// of an argument, and a named constant is text the test cannot see.
//
// This file's own documentation prescribes `HOTKEY_PREFIX := "~*"` as the way to
// make the sweep's prefix executable (see the RESIDUE block). The guard then
// rejected that very refactor, and said something untrue while doing it: "3
// registration(s) no longer use the ~* prefix", when all three still did. A
// guard that rejects the refactor its own documentation recommends is a guard
// the next maintainer deletes, so it resolves the constant instead.
function sliceStringConstants(text) {
  const consts = new Map();
  const re = /^[ \t]*(?:global[ \t]+)?([A-Za-z_]\w*)[ \t]*:=[ \t]*"((?:[^"\r\n]|"")*)"[ \t]*(?:;.*)?$/gm;
  let m;
  while ((m = re.exec(text))) consts.set(m[1], m[2].replace(/""/g, '"'));
  return consts;
}

// The same again, for constants whose value is an ARITHMETIC EXPRESSION rather
// than a literal — `VK_SWEEP_COUNT := VK_LAST - VK_FIRST + 1`. The right-hand
// side is kept as TEXT, unevaluated, because what the sweep-bound check below
// asks is whether the bound is still written in terms of the two constants
// HarnessReport() dumps; a number would answer that question wrongly either way.
function sliceNumericExprConstants(text) {
  const consts = new Map();
  const re = /^[ \t]*(?:global[ \t]+)?([A-Za-z_]\w*)[ \t]*:=[ \t]*([A-Za-z_0-9 \t+\-*/()]+?)[ \t]*(?:;.*)?$/gm;
  let m;
  while ((m = re.exec(text))) consts.set(m[1], m[2].replace(/\s+/g, ''));
  return consts;
}

// Replace bare identifiers with the string literals they were declared as.
// Quoted regions are copied through untouched, so a constant's NAME appearing
// inside some other string cannot be substituted into it.
function substituteAhkStrings(text, consts) {
  let out = '';
  for (let i = 0; i < text.length;) {
    if (text[i] === '"') {
      const start = i;
      for (i++; i < text.length; i++) {
        if (text[i] !== '"') continue;
        if (text[i + 1] === '"') { i++; continue; }   // "" is an escaped quote
        break;
      }
      out += text.slice(start, Math.min(i + 1, text.length));
      i++;
      continue;
    }
    const m = /^[A-Za-z_]\w*/.exec(text.slice(i));
    if (m) {
      out += consts.has(m[0]) ? `"${consts.get(m[0])}"` : m[0];
      i += m[0].length;
      continue;
    }
    out += text[i];
    i++;
  }
  return out;
}

// Can the "~*" prefix be PROVEN present in this hotkey name expression? Three
// readings, weakest last: the literal text, the text with string constants
// resolved, and the same with the concatenation syntax removed so `PRE . "*vk"`
// or `"~" . "*"` still reads as "~*".
function hasHotkeyPrefix(arg, consts) {
  if (arg.includes('~*')) return true;
  const resolved = substituteAhkStrings(arg, consts);
  return resolved.includes('~*') || resolved.replace(/["\s.]/g, '').includes('~*');
}

// Registrations that legitimately must NOT pass the key through, each with the
// reason it is exempt. Matched against the call's first argument.
//
// The allowlist is the price of checking the WHOLE file instead of one block:
// scoping the check to the text between two banners meant an ordinary
// extract-function refactor could carry a registration out of its view, and
// dropping "~*" there then produced a clean PASS. Every exemption has to match
// something — see assertHotkeyPrefixes — so an entry cannot outlive the
// registration it was written for and quietly widen into a hole.
const HOTKEY_PREFIX_EXEMPT = [
  [/^"\^\+v"$/, 'Ctrl+Shift+V toggles the mode and must be SWALLOWED, not passed through'],
  [/^"\^\+q"$/, 'Ctrl+Shift+Q quits and must be SWALLOWED, not passed through'],
  [/^"~"\s*\.?\s*keyName\s*\.?\s*" up"$/,
    'double-tap gesture: "~" already passes the key through, and "*" would make it\n'
    + '                fire while a modifier is held — exactly what the A_PriorKey test rejects'],
  [/^lower$/, 'letter key in VN mode: the input method REPLACES this keystroke, so it must\n'
    + '                not also reach the application (that is what makes EN mode a real passthrough)'],
  [/^"\+"\s*\.?\s*lower$/, 'ditto, the shifted half of the same pair'],
];

// Every Hotkey() in the SHIPPED FILE, not just in one block. "~" is what lets the
// key still reach the application and "*" is what makes it fire while a modifier
// is down; dropping either changes the input method in a way no vector can see,
// because none of this can be executed under test.
function assertHotkeyPrefixes(ahkSrc) {
  const src = stripAhkComments(ahkSrc);
  const consts = sliceStringConstants(src);
  const args = hotkeyFirstArgs(src).map(a => a.replace(/\s+/g, ' ').trim());
  if (args.length < HOTKEY_PREFIX_EXEMPT.length + 1) {
    die(`VietDvorak.ahk contains only ${args.length} Hotkey() call(s) — it cannot install the input\n`
      + '            method with that few, so this guard would be checking nothing.');
  }
  const unproven = [];
  const matched = new Set();
  for (const arg of args) {
    const exempt = HOTKEY_PREFIX_EXEMPT.findIndex(([re]) => re.test(arg));
    if (exempt >= 0) { matched.add(exempt); continue; }
    if (!hasHotkeyPrefix(arg, consts)) unproven.push(arg);
  }
  if (unproven.length) {
    die(`could not prove the "~*" prefix is present in ${unproven.length} registration(s) in VietDvorak.ahk:\n`
      + unproven.slice(0, 6).map(a => `              Hotkey(${a}, ...)`).join('\n') + '\n'
      + '            "~" is what lets the key still reach the application; "*" is what makes\n'
      + '            it fire while a modifier is held. Dropping either changes the shipped\n'
      + '            input method in a way no vector can see, because none of this block can\n'
      + '            be executed under test.\n'
      + '            The prefix may still be THERE and merely indirect: this reads the\n'
      + '            argument as text, resolves `NAME := "..."` string constants declared\n'
      + '            anywhere in the file, and gives up after that. A prefix built at run\n'
      + '            time (from a Map, a parameter, a function return) cannot be seen from\n'
      + '            here — if that is the shape, teach hasHotkeyPrefix() to read it, or add\n'
      + '            the call to HOTKEY_PREFIX_EXEMPT with the reason it is exempt.');
  }
  const stale = HOTKEY_PREFIX_EXEMPT.filter((_, i) => !matched.has(i));
  if (stale.length) {
    die(`${stale.length} entr${stale.length === 1 ? 'y' : 'ies'} in HOTKEY_PREFIX_EXEMPT no longer match${stale.length === 1 ? 'es' : ''} any Hotkey() call\n`
      + '            in VietDvorak.ahk:\n'
      + stale.map(([re, why]) => `              ${re}\n                (${why.split('\n')[0]})`).join('\n') + '\n'
      + '            An exemption that has outlived its registration is a permanent hole in\n'
      + '            this guard: the next call whose argument happens to match it would be\n'
      + '            waved through. If the registration is gone, delete the row; if it was\n'
      + '            reworded, reword the row with it.');
  }
}

function resolveVk(token, consts) {
  const t = token.trim();
  if (/^0[xX][0-9a-fA-F]+$/.test(t) || /^\d+$/.test(t)) return Number(t);
  if (consts.has(t)) return consts.get(t);
  return null;
}

// Read the `VK_KEEPS_SYLLABLE := Map( k, v, k, v )` literal out of the slice.
// Returns { ok: true, count, keys } or { ok: false, why }. `keys` is the list of
// virtual-key codes, or null when some key is an expression this cannot resolve
// (in which case the run-time dump out of the harness is the authority instead).
//
// This is the STRUCTURAL half of the guard below. Asking merely whether the
// identifier appears is not enough: a bare `VK_KEEPS_SYLLABLE := Map()` answers
// yes, and so does a slice cut off in the middle of a loop that would have
// filled the map in. Either way the harness gets an EMPTY keep-alive map, every
// key looks like a syllable-ender, and the digit-break vectors pass while
// testing nothing. So: find a COMPLETE literal, or say why there isn't one.
//
// The KEYS matter as much as the count, because which codes are in the map is
// exactly what no conformance vector can check for Shift (see EXPECTED_KEEPALIVE).
function keepAliveLiteral(slice) {
  const open = /(^|[^A-Za-z0-9_])VK_KEEPS_SYLLABLE[ \t]*:=[ \t]*Map[ \t]*\(/.exec(slice);
  if (!open) {
    return { ok: false, why: 'no `VK_KEEPS_SYLLABLE := Map( ... )` literal in the slice' };
  }
  let depth = 1;
  const items = [];
  let cur = '';
  let i = open.index + open[0].length;
  for (; i < slice.length; i++) {
    const c = slice[i];
    if (c === '"') {                                  // string literal
      const start = i;
      for (i++; i < slice.length && slice[i] !== '"'; i++);
      cur += slice.slice(start, i + 1);
      continue;
    }
    if (c === ';' && /\s/.test(slice[i - 1] || ' ')) { // AHK end-of-line comment
      const nl = slice.indexOf('\n', i);
      i = nl < 0 ? slice.length : nl;
      continue;
    }
    if (c === '(') { depth++; cur += c; continue; }
    if (c === ')') {
      depth--;
      if (depth === 0) { items.push(cur); break; }
      cur += c;
      continue;
    }
    if (c === ',' && depth === 1) { items.push(cur); cur = ''; continue; }
    cur += c;
  }
  if (depth !== 0) {
    return { ok: false, why: 'the `VK_KEEPS_SYLLABLE := Map(` literal is never closed inside the slice' };
  }
  const cells = items.map(s => s.trim()).filter(s => s !== '');
  if (cells.length === 0) return { ok: false, why: 'the VK_KEEPS_SYLLABLE literal is empty' };
  if (cells.length % 2 !== 0) {
    return { ok: false, why: `the VK_KEEPS_SYLLABLE literal has ${cells.length} items, which is not a whole number of key/value pairs` };
  }
  const consts = sliceConstants(slice);
  const keys = cells.filter((_, i) => i % 2 === 0).map(c => resolveVk(c, consts));
  return { ok: true, count: cells.length / 2, keys: keys.includes(null) ? null : keys };
}

// Why a missing entry matters at all — shared by both wordings below.
const KEEPALIVE_STAKES =
    'No conformance vector can catch this and none ever will: the\n'
  + '            harness drives the engines with CHARACTERS, and none of these\n'
  + '            codes is reachable from a character — nobody types a letter by\n'
  + '            pressing Shift on its own. On a real keyboard the effect is that\n'
  + '            every Shift press ends the syllable, so "DDaij." commits after\n'
  + '            the first D and "xin TIEENGS" stops producing "xin TIẾNG" — while\n'
  + '            this script would still print PASS. Hence the structural check.\n';

// EXPECTED_KEEPALIVE ⊆ actual, naming exactly what went missing. `where` says
// whether this is the text check-parity parsed or the map AutoHotkey loaded —
// both are checked, because a literal that parses one way and loads another is
// itself the bug.
//
// Only the run-time verdict is AUTHORITATIVE, and only it may prescribe a remedy.
// The parse-time one reads a LITERAL, and a literal can be short of the map with
// nothing having been removed: `Map(0x08, true)` plus a builder that adds the
// rest still loads all five. Telling a maintainer to delete the four "missing"
// entries from EXPECTED_KEEPALIVE in that situation would permanently disable the
// Shift / VK_PACKET guard — the one check no conformance vector can replace — to
// fix a shape problem in which nothing was ever removed. A wrong remedy printed
// with authority is worse than no message, so the parse-time wording states only
// what it saw and points at the run-time check for the verdict.
function assertKeepAliveShape(keys, where, authoritative) {
  const have = new Set(keys);
  const missing = EXPECTED_KEEPALIVE.filter(([vk]) => !have.has(vk));
  if (!missing.length) return;
  const names = missing.map(([vk, name]) => `0x${hex2(vk)} (${name})`).join(', ');
  if (authoritative) {
    die(`syllable-break rule (${where}): VK_KEEPS_SYLLABLE no longer keeps ${names}.\n`
      + '            ' + KEEPALIVE_STAKES
      + '            If the removal is intended, the entry has to leave\n'
      + '            EXPECTED_KEEPALIVE in check-parity.mjs in the same commit, with\n'
      + '            the reason written down.');
  }
  die(`syllable-break rule (${where}): the VK_KEEPS_SYLLABLE literal this script can\n`
    + `            read does not contain ${names}.\n`
    + '            EITHER those codes were removed, OR the map is no longer a single\n'
    + '            literal — a builder loop, a second Map() merged in, or a .Set()\n'
    + '            call would load them without them ever appearing here. See\n'
    + '            keepAliveLiteral(), which reads the literal and nothing else.\n'
    + '            ' + KEEPALIVE_STAKES
    + '            THIS CHECK IS NOT THE AUTHORITY on which of the two it is, and it\n'
    + '            stops the run before the two that are: assertKeepAliveShape("as\n'
    + '            loaded by AutoHotkey") and the HARNESS_KEEPALIVE_COUNT assertion in\n'
    + '            the generated harness both read the map AutoHotkey really built.\n'
    + '            Settle it by LOOKING at VK_KEEPS_SYLLABLE in VietDvorak.ahk: if the\n'
    + '            codes are still there and only the shape changed, the map has to go\n'
    + '            back to one literal keepAliveLiteral() can read (or keepAliveLiteral\n'
    + '            has to learn the new shape) — after which those two run-time checks\n'
    + '            give the real verdict.\n'
    + '            Do NOT delete entries from EXPECTED_KEEPALIVE to make this go away.\n'
    + '            If the map is merely BUILT rather than literal, deleting them would\n'
    + '            switch the Shift / VK_PACKET guard off for good while nothing had\n'
    + '            been removed at all.');
}

// The complement: actual ∩ DENIED_KEEPALIVE must be EMPTY. Same shape as the
// subset assertion above, opposite direction, and deliberately narrow — it says
// nothing about additions in general, only about the codes that commit text or
// move the caret.
function assertKeepAliveDenylist(keys, where) {
  const have = new Set(keys);
  const banned = DENIED_KEEPALIVE.filter(([vk]) => have.has(vk));
  if (!banned.length) return;
  const names = banned.map(([vk, name]) => `0x${hex2(vk)} (${name})`).join(', ');
  die(`syllable-break rule (${where}): VK_KEEPS_SYLLABLE keeps the syllable alive\n`
    + `            across ${names}.\n`
    + '            ADDING a keep-alive is normally fine and is only noted, because a\n'
    + '            new modifier that takes part in typing a letter has to keep the\n'
    + '            buffer. These codes are not that: each one either commits text or\n'
    + '            moves the caret, which is the reason VietDvorak.ahk\'s own break-rule\n'
    + '            banner gives for ending the syllable ("chèn ký tự mà script không\n'
    + '            biết, hoặc dời con trỏ đi chỗ khác"). Keeping the buffer across one\n'
    + '            of them leaves it describing text the caret has left, and the next\n'
    + '            SyncToScreen backspaces into whatever is now in front of it.\n'
    + '            No conformance vector can catch this either: the harness drives the\n'
    + '            engines with characters and none of these codes is reachable from\n'
    + '            one. If a key here genuinely must keep the syllable, say why in\n'
    + '            DENIED_KEEPALIVE in check-parity.mjs in the same commit.');
}

// Returns { text, keepAliveCount, keepAliveKeys }.
function sliceAhkBreakRule(src) {
  const b = src.indexOf(AHK_BREAK_BANNER);
  if (b < 0) die(`banner "${AHK_BREAK_BANNER}" not found in VietDvorak.ahk — the slice markers are stale`);
  const rest = src.slice(lineStartOf(src, b));
  const stop = AHK_BREAK_STOP.exec(rest);
  if (!stop) die('no registration statement found after the syllable-break banner in VietDvorak.ahk');
  const text = rest.slice(0, stop.index);
  // Whole words, and for VkEndsSyllable the DECLARATION rather than a mention:
  // the harness CALLS that predicate instead of restating the rule, so if it is
  // renamed or moved out of this slice the harness must refuse to build. A
  // substring test would not do — it accepts "VkEndsSyllableRenamed" and hands
  // AutoHotkey a harness that calls a function nobody defines.
  for (const [name, re] of [
    ['VK_FIRST', /\bVK_FIRST\b/],
    ['VK_LAST', /\bVK_LAST\b/],
    ['VK_LETTER_FIRST', /\bVK_LETTER_FIRST\b/],
    ['VK_LETTER_LAST', /\bVK_LETTER_LAST\b/],
    ['VK_KEEPS_SYLLABLE', /\bVK_KEEPS_SYLLABLE\b/],
    ['the VkEndsSyllable() declaration', /^VkEndsSyllable[ \t]*\(/m],
  ]) {
    if (!re.test(text)) die(`syllable-break slice is missing ${name} — the markers are stale`);
  }
  const keep = keepAliveLiteral(text);
  if (!keep.ok) {
    die(`syllable-break slice: ${keep.why}.\n`
      + '            The keep-alive map has to be a literal this script can read and\n'
      + '            count, because the count is asserted inside the harness at run\n'
      + '            time — that assertion is the only thing standing between a\n'
      + '            truncated slice and a green run on an untested break rule.\n'
      + `            Either keep the literal in VietDvorak.ahk under the "${AHK_BREAK_BANNER}"\n`
      + '            banner, or teach keepAliveLiteral() the new shape.');
  }
  // Fails before AutoHotkey is even started when the codes are plain literals or
  // slice-local constants. When they are neither, keep.keys is null and the same
  // assertion runs on the map AutoHotkey actually loaded (see runAhkVectors).
  if (keep.keys) assertKeepAliveShape(keep.keys, 'as sliced from VietDvorak.ahk', false);
  // The registration block that follows the rule cannot be executed under test —
  // running it means installing a real keyboard hook — so it is read instead.
  const endIdx = rest.indexOf(AHK_REGISTRATION_END, stop.index);
  if (endIdx < 0) {
    die(`banner "${AHK_REGISTRATION_END}" not found after the registration block in `
      + 'VietDvorak.ahk — the markers are stale');
  }
  return {
    text,
    keepAliveCount: keep.count,
    keepAliveKeys: keep.keys,
    registration: rest.slice(stop.index, endIdx),
  };
}

// ---------------------------------------------------------------------------
// THE RESIDUE: the registration block, the one part of the break rule that no
// harness can execute.
//
// Everything from the `Loop` line down — the loop's iteration COUNT, the `~*`
// flags, the hotkey-name expression, the mouse-button loop and the Backspace
// hotkey — INSTALLS the rule rather than stating it, and installing it means
// creating a real keyboard hook on the developer's machine. So it sits outside
// both slices and can only be READ, never run.
//
// Two of those expressions are DATA, not control flow, and one of them is a
// SECOND way to narrow the sweep. EXPECTED_SWEEP_RANGE reads VK_FIRST/VK_LAST out
// of HarnessReport() and its message promises to catch a narrowed sweep — but
// what decides how many codes actually get hooked is `Loop (VK_LAST - VK_FIRST +
// 1)`, and rewriting THAT as `Loop (0xDF - VK_FIRST + 1)` leaves VK_LAST at 0xFE,
// so the report still says 0x08..0xFE and the promise is not kept. Same for the
// `~*` in the hotkey name: without `~` the key stops reaching the application,
// without `*` it stops firing while a modifier is down.
//
// A text check is second best to an executed one and is worth labelling as such:
// it verifies the bound is still WRITTEN in terms of the two constants the
// harness reports, not that it evaluates to the right number. Making it an
// executed assertion needs an edit to VietDvorak.ahk — hoisting the bound and the
// hotkey prefix above the slice boundary (e.g. `VK_SWEEP_COUNT := VK_LAST -
// VK_FIRST + 1` and `HOTKEY_PREFIX := "~*"` under the break banner) so
// HarnessReport() could dump them — which is not made here.
//
// BOTH HALVES OF THAT EDIT PASS THESE CHECKS TODAY, which is the only honest
// state for a file that recommends it: `HOTKEY_PREFIX := "~*"` is resolved by
// sliceStringConstants() before the prefix is looked for, and `Loop
// VK_SWEEP_COUNT` is resolved by sliceNumericExprConstants() before the bound is
// matched. A prescription its own guard rejects is a prescription nobody can
// follow, and this file used to make exactly that recommendation twice. What is
// still NOT done is the executed half — teaching HarnessReport() to dump the two
// hoisted constants so the check becomes a comparison of values rather than of
// text. That edit belongs to VietDvorak.ahk and is not made here.
// ---------------------------------------------------------------------------

// AHK end-of-line comments, so a `Hotkey(` mentioned in prose is not mistaken for
// a registration.
function stripAhkComments(text) {
  return text.split('\n').map(l => l.replace(/(^|[ \t]);.*$/, '$1')).join('\n');
}

// First argument of every Hotkey() call in the block. Paren- and quote-aware, so
// `Hotkey(Format("~*vk{:02X}", vk), ResetBuffer)` yields the whole Format(...)
// rather than stopping at the comma inside it.
function hotkeyFirstArgs(text) {
  const args = [];
  const re = /\bHotkey[ \t]*\(/g;
  let m;
  while ((m = re.exec(text))) {
    let depth = 1, arg = '';
    for (let i = m.index + m[0].length; i < text.length; i++) {
      const c = text[i];
      if (c === '"') {
        const s = i;
        for (i++; i < text.length && text[i] !== '"'; i++);
        arg += text.slice(s, i + 1);
        continue;
      }
      if (c === '(') { depth++; arg += c; continue; }
      if (c === ')') { depth--; if (depth === 0) break; arg += c; continue; }
      if (c === ',' && depth === 1) break;
      arg += c;
    }
    args.push(arg.trim());
  }
  return args;
}

// The `{ ... }` body that starts at or after `from`, brace-matched. Quote-aware;
// callers pass comment-stripped text so a brace in prose cannot open a block.
function braceBody(text, from) {
  const open = text.indexOf('{', from);
  if (open < 0) return null;
  let depth = 0;
  for (let i = open; i < text.length; i++) {
    const c = text[i];
    if (c === '"') { for (i++; i < text.length && text[i] !== '"'; i++); continue; }
    if (c === '{') depth++;
    else if (c === '}') { depth--; if (depth === 0) return text.slice(open + 1, i); }
  }
  return null;
}

function ahkFunctionBody(src, name) {
  const m = new RegExp(`^${name}[ \\t]*\\([^)]*\\)[ \\t]*\\{`, 'm').exec(src);
  return m ? braceBody(src, m.index) : null;
}

// Does this block INSTALL a hotkey — directly, or through a function it calls?
// One level of indirection is followed on purpose: extracting the body of the
// sweep into `RegisterSweepKey(vk)` is an ordinary refactor and must not read as
// "the sweep registers nothing".
function installsHotkey(body, src, depth = 2) {
  if (/\bHotkey[ \t]*\(/.test(body)) return true;
  if (depth <= 0) return false;
  const called = new Set([...body.matchAll(/\b([A-Za-z_]\w*)[ \t]*\(/g)].map(m => m[1]));
  for (const name of called) {
    const fn = ahkFunctionBody(src, name);
    if (fn && installsHotkey(fn, src, depth - 1)) return true;
  }
  return false;
}

function assertRegistration(text, ahkSrc) {
  const src = stripAhkComments(text);
  const loop = /^Loop\b(.*)$/m.exec(src);
  if (!loop) die('no `Loop` line in the registration block of VietDvorak.ahk — the markers are stale');
  // Whitespace-normalised and brace-stripped: reformatting is not a regression,
  // replacing a constant with a number is.
  const bound = loop[1].replace(/\{[ \t]*$/, '').replace(/\s+/g, '');
  // A bound written as a NAMED constant is the refactor this file's own RESIDUE
  // block prescribes — `VK_SWEEP_COUNT := VK_LAST - VK_FIRST + 1`, hoisted so
  // HarnessReport() could one day dump it — and a guard that rejects the edit its
  // own documentation recommends is a guard the next maintainer deletes. So a
  // bare identifier is RESOLVED through its declaration (anywhere in the file,
  // comments stripped) and the resolved text is what the pattern sees. Two
  // passes, the same one-level-of-indirection policy installsHotkey() uses.
  //
  // Resolving rather than accepting the name is the whole point: `VK_SWEEP_COUNT
  // := 0xDF - VK_FIRST + 1` — the narrowing this check exists to catch, wearing
  // the refactor's clothes — resolves to text the pattern still rejects.
  const exprConsts = sliceNumericExprConstants(stripAhkComments(ahkSrc));
  let resolved = bound;
  for (let depth = 0; depth < 2 && /^[A-Za-z_]\w*$/.test(resolved) && exprConsts.has(resolved); depth++) {
    resolved = exprConsts.get(resolved);
  }
  if (!/^\(?VK_LAST-VK_FIRST\+1\)?$/.test(resolved)) {
    die(`the hotkey sweep is registered as "Loop${loop[1].replace(/\s+$/, '')}", not over\n`
      + '            VK_LAST - VK_FIRST + 1.\n'
      + (resolved === bound ? ''
        : `            ("${bound}" is declared as "${resolved}", which is what was checked.)\n`)
      + '            That expression is the sweep\'s REAL bound and it lives outside both\n'
      + '            slices, so nothing executes it. EXPECTED_SWEEP_RANGE only sees\n'
      + '            VK_FIRST/VK_LAST as HarnessReport() dumps them — narrowing the loop\n'
      + '            instead leaves those constants untouched, un-hooks every code past\n'
      + '            the new bound, and reports 0x08..0xFE all the same.\n'
      + '            A NAMED bound is fine and is resolved before this test — `Loop\n'
      + '            VK_SWEEP_COUNT` passes while VK_SWEEP_COUNT is declared as\n'
      + '            `VK_LAST - VK_FIRST + 1`, which is the refactor the RESIDUE block above\n'
      + '            recommends. What is refused is a bound that stops being derived from\n'
      + '            the two constants the harness reports, under any name.\n'
      + '            If it must stop being derived from them, this check has to be replaced\n'
      + '            by one that can still see a narrowing.');
  }
  // What the sweep DOES, asked of the loop itself rather than of the text around
  // it. The block also holds the five mouse registrations and the Backspace one,
  // so "this block registers something" stayed true with the sweep's own
  // Hotkey() call moved out of it — and a "~*" check scoped to the block then
  // had nothing of the sweep left to look at.
  const body = braceBody(src, loop.index);
  if (body === null) {
    die('the hotkey sweep in VietDvorak.ahk has no `{ ... }` body.\n'
      + '            The sweep is what installs the syllable-break rule on every virtual key.\n'
      + '            Nothing here can execute it, so what it contains is read instead.');
  }
  if (!installsHotkey(body, stripAhkComments(ahkSrc))) {
    die('the hotkey sweep loop in VietDvorak.ahk registers nothing.\n'
      + '            Its body holds no Hotkey() call, and neither does any function it calls.\n'
      + '            The loop is the ONLY thing that installs the syllable-break rule on the\n'
      + '            keyboard: with it empty, VietDvorak.ahk still passes every conformance\n'
      + '            vector — Transform() is untouched — and stops resetting the buffer on\n'
      + '            every non-letter key, which is the "tri.f" corruption this spec exists\n'
      + '            to pin. Nothing can execute this block, so its CONTENT is the check.');
  }
  // The "~*" prefix itself is checked over the whole file (assertHotkeyPrefixes),
  // not over this block: a registration one line the other side of the banner
  // below is still a registration in the shipped input method.
}

// Notes worth printing on an otherwise clean run — see assertClean().
const harnessNotes = [];

// The raw text is scanned, comments and all: that is the conservative reading
// and it stays the trigger, because a stripper can be fooled and the thing being
// prevented is a real keyboard hook on a live machine.
//
// But the raw reading cannot DIAGNOSE. The syllable-break region is ~35 lines of
// prose ABOUT hotkey registration ("Hotkey thì mặc định KHÔNG bị kích hoạt..."),
// so a comment-only edit that happens to write `Hotkey(` used to abort the run
// with a diagnosis that was simply false — "the slice markers must have drifted
// into runtime code ... Fix the markers first" — sending a maintainer to look
// for a marker problem that does not exist.
//
// So: raw scan fires, then the same scan runs on the comment-stripped text. If
// nothing survives, the token is in a comment, a comment installs no hook, and
// the run continues with the fact stated rather than swallowed. If anything
// survives, it is executable and the original refusal stands — naming which of
// the hits was the real one.
function assertClean(text, forbidden, what) {
  const hits = forbidden.filter(f => text.includes(f));
  if (!hits.length) return;
  const stripped = stripAhkComments(text);
  const live = hits.filter(f => stripped.includes(f));
  if (!live.length) {
    harnessNotes.push(`${what}: ${hits.join(', ')} appears only in a COMMENT — not executable, run continued`);
    return;
  }
  const inComment = hits.filter(f => !live.includes(f));
  die(`REFUSING TO RUN: ${what} contains ${live.join(', ')} in EXECUTABLE code.\n`
    + (inComment.length ? `            (${inComment.join(', ')} also appears, but only in a comment.)\n` : '')
    + '            The slice markers must have drifted into VietDvorak.ahk\'s runtime code.\n'
    + '            Running it could install a real keyboard hook. Fix the markers first.');
}

