// ---------------------------------------------------------------------------
// CHARACTER -> VIRTUAL KEY. The bridge, and the reason there has to be one.
//
// The harness types characters. VietDvorak.ahk's syllable-break rule is about
// VIRTUAL KEYS. For A-Z, 0-9 and space the two coincide — the virtual-key code
// IS the uppercase ASCII code — and that coincidence used to be the whole of
// the harness's model: `vk := Ord(StrUpper(ch))`.
//
// It is false for punctuation, and silently so. "." is VK_OEM_PERIOD (0xBE),
// not 0x2E; "-" is VK_OEM_MINUS (0xBD), not 0x2D. An Ord()-based harness asks
// about codes no keyboard ever sends, so a keep-alive entry added at the REAL
// code changed nothing it could see: adding 0xBE to VK_KEEPS_SYLLABLE — which
// on a live keyboard stops "." ending a syllable and re-breaks the exact bug
// "tri.f" is in the spec to pin — used to produce a clean PASS.
//
// So: a real map. Every character the spec's integration vectors use is here
// with its true code, which is what makes the harness's guards able to fire.
//
// The codes are the US layout's, which is what the OEM_* names are defined
// against; a different layout puts a given character on a different OEM code.
// That does not weaken the check: the rule treats the whole OEM block alike, so
// what is being verified — "no punctuation key keeps the syllable alive" — is
// layout-independent, and the map covers every character in the block, so a
// keep-alive anywhere in it is caught whichever key the layout calls it.
// ---------------------------------------------------------------------------
const OEM_PUNCTUATION = [
  [0xBA, ';:', 'VK_OEM_1'],
  [0xBB, '=+', 'VK_OEM_PLUS'],
  [0xBC, ',<', 'VK_OEM_COMMA'],
  [0xBD, '-_', 'VK_OEM_MINUS'],
  [0xBE, '.>', 'VK_OEM_PERIOD'],
  [0xBF, '/?', 'VK_OEM_2'],
  [0xC0, '`~', 'VK_OEM_3'],
  [0xDB, '[{', 'VK_OEM_4'],
  [0xDC, '\\|', 'VK_OEM_5'],
  [0xDD, ']}', 'VK_OEM_6'],
  [0xDE, '\'"', 'VK_OEM_7'],
];

function buildCharVk() {
  const m = new Map();
  for (let i = 0; i < 26; i++) {
    m.set(String.fromCharCode(0x41 + i), 0x41 + i);   // A-Z
    m.set(String.fromCharCode(0x61 + i), 0x41 + i);   // a-z — same physical key
  }
  for (let d = 0; d <= 9; d++) m.set(String(d), 0x30 + d);
  m.set(' ', 0x20);
  for (const [vk, chars] of OEM_PUNCTUATION) for (const ch of chars) m.set(ch, vk);
  return m;
}
const CHAR_VK = buildCharVk();

const hex2 = (n) => n.toString(16).toUpperCase().padStart(2, '0');

// The AHK half of the same table, folded to one entry per physical key. Written
// INTO the harness rather than kept beside it, so there is one table and not two.
function charVkAhkLiteral() {
  const folded = new Map();
  for (const [ch, vk] of CHAR_VK) {
    const key = ch.toUpperCase();
    if (!folded.has(key)) folded.set(key, vk);
  }
  const lit = (ch) => '"' + ch.replace(/`/g, '``').replace(/"/g, '`"') + '"';
  const rows = [...folded].map(([ch, vk]) => `    ${lit(ch)}, 0x${hex2(vk)}`);
  return `global HARNESS_CHAR_VK := Map(\n${rows.join(',\n')}\n)\n`;
}

// The keep-alive codes that NO character-driven harness can ever reach, and so
// the ones no conformance vector can ever pin. Nobody types a character by
// pressing Shift; VK_PACKET is not a key at all; Backspace is handled by its own
// hotkey. Deleting any of them from VK_KEEPS_SYLLABLE breaks the shipped input
// method — every Shift press would end the syllable, so "DDaij." would commit
// after the first "D" and "xin TIEENGS" would stop producing "xin TIẾNG" — while
// every vector in the spec still passes. Hence: asserted by NAME, structurally.
//
// Deliberately a SUBSET assertion, not an equality one. Removing an entry is
// invisible to behaviour and must fail here; ADDING one is not symmetric —
// adding a keep-alive at a code some character sits on is caught by the harness
// itself (it refuses to run, naming the code), and adding one at a code no
// character can reach is a legitimate edit, e.g. a new modifier that has to keep
// the syllable alive. Equality would reject that edit, and a guard that rejects
// valid edits is a guard the next maintainer deletes. Extras are reported, not
// failed.
const EXPECTED_KEEPALIVE = [
  [0x08, 'Backspace'],
  [0x10, 'VK_SHIFT'],
  [0xA0, 'VK_LSHIFT'],
  [0xA1, 'VK_RSHIFT'],
  [0xE7, 'VK_PACKET'],
];

// The other half of that asymmetry, and the line the subset assertion above does
// not draw. Permissiveness is right for a new MODIFIER — 0xE5 VK_PROCESSKEY takes
// part in producing a letter and has to keep the buffer, so it passes with an
// advisory note. It is wrong for a key that COMMITS TEXT OR MOVES THE CARET.
// VietDvorak.ahk's own break-rule banner gives exactly that as the reason the
// syllable must end: every other key "hoặc chèn ký tự mà script không biết, hoặc
// dời con trỏ đi chỗ khác". A keep-alive on one of these leaves g_buffer
// describing text the caret has already left, and the next SyncToScreen sends
// backspaces into whatever is now in front of it — the "tri.f" buffer-desync
// class this whole spec exists to pin, re-created at a code no vector can reach.
// Hence: refused by name, the same way the missing entries above are.
const DENIED_KEEPALIVE = [
  [0x09, 'Tab'],
  [0x0D, 'Enter'],
  [0x1B, 'Esc'],
  [0x21, 'PageUp'],
  [0x22, 'PageDown'],
  [0x23, 'End'],
  [0x24, 'Home'],
  [0x25, 'Left'],
  [0x26, 'Up'],
  [0x27, 'Right'],
  [0x28, 'Down'],
  [0x2D, 'Insert'],
  [0x2E, 'Delete'],
];

// The denylist only bites while it stays disjoint from the list above: moving a
// code into EXPECTED_KEEPALIVE is precisely the edit it exists to stop, and the
// subset check would then wave it through. Checked here, at load, so the two
// tables cannot quietly contradict each other.
for (const [vk, name] of DENIED_KEEPALIVE) {
  if (EXPECTED_KEEPALIVE.some(([e]) => e === vk)) {
    die(`0x${hex2(vk)} (${name}) is in BOTH EXPECTED_KEEPALIVE and DENIED_KEEPALIVE.\n`
      + '            A key that commits text or moves the caret cannot also be a\n'
      + '            keep-alive key. If it genuinely must become one, the argument\n'
      + '            belongs in DENIED_KEEPALIVE next to the entry being removed —\n'
      + '            not in a silent overlap that disables the guard.');
  }
}

// The same blind spot, one level up: the swept RANGE. Characters only reach
