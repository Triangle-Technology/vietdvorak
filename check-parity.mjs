function die(msg) {
  console.error(`check-parity: ${msg}`);
  process.exit(2);
}

function read(path, what) {
  try {
    return readFileSync(path, 'utf8');
  } catch (err) {
    die(`cannot read ${path} (${what}): ${err.message}`);
  }
}

// Locate a begin/end marker pair. `from`..`to` spans the markers themselves (so
// the caller can splice a replacement straight in); `from`..`innerEnd` is the
// content up to but not including the end marker.
function markedRegion(html, begin, end, what) {
  const from = html.indexOf(begin);
  if (from < 0) die(`marker "${begin}" not found in practice.html (${what})`);
  const innerEnd = html.indexOf(end, from);
  if (innerEnd < 0) die(`marker "${end}" not found after "${begin}" in practice.html (${what})`);
  return { from, innerEnd, to: innerEnd + end.length };
}

// ---------------------------------------------------------------------------
// JS side: pull the engine, the apply path AND the word-list guard out of
// practice.html rather than keeping a second copy here.
//
// The engine sits between explicit markers. Everything else is ordinary page
// code — so it is sliced by DECLARATION NAME, and the slice is proved correct by
// evaluating it: a wrong cut cannot produce a working applyKey(). transform()
// alone would leave the syllable-break rule untested, and that rule is the one
// that corrupts already-committed text when it drifts.
//
// checkWordListsTypeable() is pulled across for a different reason: it is a
// genuine executable guard that the trainer's TARGETS are reachable through the
// engine, but it used to be wired only into runSelfTests(), which needs a
// browser tab and reports to console.error. Its own comment says "Nothing
// executable used to check this" — and that stayed true of the command the
// project tells people to run after ANY engine change. It is not true any more.
// ---------------------------------------------------------------------------

// Index of a marker that provably PRECEDES a later anchor whose text is not
// unique. `for (const [bv, tones] of Object.entries(VOWELS))` occurs twice in
// practice.html — once inside the engine block deriving UPPER_VOWELS, once below
// filling REVERSE_VOWEL — and a bare indexOf would silently cut the first one and
// hand the evaluator a REVERSE_VOWEL nothing ever filled. Still a marker, never a
// line number: it dies when the marker is gone.
function anchorAt(src, needle, what) {
  const i = src.indexOf(needle);
  if (i < 0) die(`anchor "${needle}" not found in practice.html (${what})`);
  return i;
}

// Balanced-brace slice starting at a declaration anchor. Skips braces inside
// strings and comments; regex literals containing braces would defeat it, which
// is why the result is always eval-checked by the caller. `from` bounds the
// search for anchors that are not unique — see anchorAt().
function sliceJsBlock(src, anchor, what, from = 0) {
  const start = src.indexOf(anchor, from);
  if (start < 0) die(`declaration "${anchor}" not found in practice.html (${what})`);
  let depth = 0, seen = false;
  for (let i = start; i < src.length; i++) {
    const c = src[i], n = src[i + 1];
    if (c === '/' && n === '/') { i = src.indexOf('\n', i); if (i < 0) break; continue; }
    if (c === '/' && n === '*') { i = src.indexOf('*/', i); if (i < 0) break; i++; continue; }
    if (c === "'" || c === '"' || c === '`') {
      const quote = c;
      for (i++; i < src.length; i++) {
        if (src[i] === '\\') { i++; continue; }
        if (src[i] === quote) break;
      }
      continue;
    }
    if (c === '{') { depth++; seen = true; }
    else if (c === '}') { depth--; if (seen && depth === 0) return src.slice(start, i + 1); }
  }
  die(`unbalanced braces while slicing "${anchor}" from practice.html (${what})`);
}

function sliceJsLine(src, re, what) {
  const m = re.exec(src);
  if (!m) die(`${what}: no line matching ${re} in practice.html`);
  return m[0];
}

// isResetChar is exported as well as used: it IS the JS side's break rule, and
// the AHK side's break rule is swept against it key by key (checkBreakSweep).
// checkWordListsTypeable is exported because this script RUNS it — see below.
const JS_EXPORTS = ['transform', 'resetTelexState', 'applyKey', 'isResetChar', 'checkWordListsTypeable'];
// WORD_LISTS comes across for the same reason one level down: the guard says how
// many spellings it checked, and "how many are there" has to come from the LISTS
// rather than from the guard's own count — and planting a probe in them is how
// the guard's comparison is proved to still compare (see checkWordLists). Listed
// apart from the functions because the "is it a function?" check below is what
// proves the slice produced code rather than a name.
const JS_VALUE_EXPORTS = ['WORD_LISTS'];

// Text that MUST be inside the engine markers. Every other slice below is taken
// by declaration name and dies when the name is gone; the marked region is the
// one that can resolve to nothing at all — move END_MARKER up against
// BEGIN_MARKER and the region is legal, empty, and hands the evaluator a page
// with no engine in it. The failure downstream would then be a ReferenceError
// about transform(), which reads like practice.html is broken rather than like
// the markers are. An empty slice is never a clean extraction, so it is named
// here instead.
const ENGINE_REQUIRED_TEXT = [
  ['function transform(', 'the engine itself'],
  ['const VOWELS', 'the vowel/tone table every vector walks'],
];

function loadJsEngine(html) {
  const { from, innerEnd } = markedRegion(html, BEGIN_MARKER, END_MARKER, 'engine');
  const engineRegion = html.slice(from, innerEnd);
  const missingEngine = ENGINE_REQUIRED_TEXT.filter(([needle]) => !engineRegion.includes(needle));
  if (missingEngine.length) {
    die(`the region between "${BEGIN_MARKER}" and "${END_MARKER}" in practice.html\n`
      + `            is ${engineRegion.trim().length} character(s) long and is missing:\n`
      + missingEngine.map(([needle, what]) => `              ${needle}   (${what})`).join('\n') + '\n'
      + '            The markers are stale, or the block was emptied. Either way every\n'
      + '            vector below would be run against an engine that is not there.');
  }
  // The hint speller fills REVERSE_VOWEL with a loop header that also appears
  // inside the engine block; start those two searches past the ambiguity.
  const reverse = anchorAt(html, 'const REVERSE_VOWEL', 'hint speller');
  const parts = [
    engineRegion,
    sliceJsLine(html, /^const LETTER_KEY = .*$/m, 'break rule'),
    sliceJsBlock(html, 'function isResetChar(', 'break rule'),
    sliceJsBlock(html, 'function applyKey(', 'apply path'),
    // Everything from here down exists so checkWordListsTypeable() can run: the
    // speller that produces the hint, the lists it spells, and the replay path.
    // Order matters — the two loops below execute at evaluation time, so the
    // tables they read have to be declared before them.
    sliceJsBlock(html, 'function stripChar(', 'word-list guard'),
    sliceJsBlock(html, 'function isSyllableChar(', 'word-list guard'),
    sliceJsBlock(html, 'const VOWEL_BASE_TO_KEYS = {', 'hint speller'),
    sliceJsLine(html, /^const TONE_TO_KEY = .*$/m, 'hint speller'),
    sliceJsLine(html, /^const REVERSE_VOWEL = .*$/m, 'hint speller'),
    sliceJsBlock(html, 'for (const [bv, tones] of Object.entries(VOWELS))', 'hint speller', reverse),
    sliceJsBlock(html, 'for (const [bv, tones] of Object.entries(UPPER_VOWELS))', 'hint speller', reverse),
    sliceJsBlock(html, 'function wordToTelex(', 'hint speller'),
    sliceJsBlock(html, 'function wordToTelexLateTone(', 'hint speller'),
    sliceJsBlock(html, 'const WORD_LISTS = {', 'word lists'),
    sliceJsBlock(html, 'function replaySpelling(', 'word-list guard'),
    sliceJsBlock(html, 'function checkWordListsTypeable(', 'word-list guard'),
  ];
  let engine;
  const names = [...JS_EXPORTS, ...JS_VALUE_EXPORTS];
  try {
    // eslint-disable-next-line no-new-func
    engine = new Function(`${parts.join('\n\n')}\nreturn { ${names.join(', ')} };`)();
  } catch (err) {
    die(`extracted practice.html code failed to evaluate: ${err.message}`);
  }
  for (const name of JS_EXPORTS) {
    if (typeof engine[name] !== 'function') die(`extracted practice.html code does not define ${name}()`);
  }
  for (const name of JS_VALUE_EXPORTS) {
    if (engine[name] === undefined) die(`extracted practice.html code does not define ${name}`);
  }
  return engine;
}

// A target the trainer's own hint cannot spell back. PLANTED IN THE WORD LISTS
// and required to come back out as a named failure — same loop, same spellers,
// same comparison the real entries get, which is the only way to prove that
// comparison still compares.
//
// "as" is that target because of the escape rule the spec pins ("ass" -> "as"):
// the only key sequence that produces the literal text "as" is "ass", and the
// hint speller never emits it, so replaying wordToTelex("as") gives "á". It is
// the probe rather than the documented "khỏe" case deliberately — "khỏe" is only
// unreachable while TONE_PLACEMENT_MODERN is true, so flipping that legitimately
// would turn the probe into a false alarm about something else entirely.
const UNTYPEABLE_PROBE = 'as';

// The word lists are TARGETS, not engine behaviour, so no conformance vector
// reaches them — and a rule change that is perfectly consistent with the spec can
// still leave a target the engine can never produce, i.e. a trainer level nobody
// can finish, on a green run. practice.html owns the guard; this runs it and
// fails on it, the same treatment applyKey() and isResetChar() already get.
//
// "Owns the guard" is exactly why `checked === 0` was not enough of an
// anti-vacuity check. check-parity PRINTS that count as a claim — "168 WORD_LISTS
// spellings replay to their target" — and a loop that skipped a level, or a
// comparison that had been defanged to `got !== undefined`, still returns a
// plausible non-zero `checked` with an empty `failures`. So the count is checked
// against the LISTS (exported alongside the guard: 2 per entry, because both
// hinted orders are replayed) and the comparison is checked against a spelling
// that must fail. A guard nobody can prove ran is a sentence this file must not
// print.
function checkWordLists(js) {
  let out;
  try {
    out = js.checkWordListsTypeable();
  } catch (err) {
    die(`practice.html's checkWordListsTypeable() threw: ${err.message}`);
  }
  if (!out || !Array.isArray(out.failures) || typeof out.checked !== 'number') {
    die('practice.html\'s checkWordListsTypeable() no longer returns { checked, failures } —\n'
      + '            check-parity.mjs runs it and reads both fields.');
  }
  const levels = Object.entries(js.WORD_LISTS || {});
  if (!levels.length) die('practice.html\'s WORD_LISTS has no levels at all.');
  let entries = 0;
  for (const [level, words] of levels) {
    if (!Array.isArray(words) || words.length === 0) {
      die(`practice.html's WORD_LISTS level "${level}" is empty — a level nobody can\n`
        + '            practise passes every guard in this file vacuously.');
    }
    entries += words.length;
  }
  const wanted = 2 * entries;
  if (out.checked !== wanted) {
    die(`practice.html's checkWordListsTypeable() checked ${out.checked} spelling(s); WORD_LISTS holds\n`
      + `            ${entries} entr${entries === 1 ? 'y' : 'ies'} across ${levels.length} level(s), which is ${wanted} spellings — both hinted\n`
      + '            orders per entry, because targetKeyHint() prints both.\n'
      + '            check-parity RUNS that guard and PRINTS its count as a claim, so the\n'
      + '            count has to come from the lists rather than from the guard itself: a\n'
      + '            loop that skips a level, or one that stops replaying the late-tone\n'
      + '            order, still returns a plausible number and an empty failure list.\n'
      + '            If the guard is meant to check something other than 2 per entry, this\n'
      + '            assertion has to change in the same commit and say what it now means.');
  }
  // ...and that the guard still REPORTS. The count above proves it looked at
  // every entry; it does not prove it can still tell a bad one from a good one,
  // and a comparison quietly weakened to `got !== undefined` returns the same
  // reassuring 168/168. So an untypeable target is planted in each level in turn
  // and the guard has to name it. This is the only assertion here that runs the
  // guard's comparison in ANGER, and it is per-level because a loop that skips a
  // level is caught by the count only while the level is non-empty.
  for (const [level, words] of levels) {
    words.push(UNTYPEABLE_PROBE);
    let probed;
    try {
      probed = js.checkWordListsTypeable();
    } finally {
      words.pop();
    }
    const named = (probed.failures || []).filter(f => String(f).includes(`"${UNTYPEABLE_PROBE}"`));
    if (probed.checked !== wanted + 2 || named.length === 0) {
      die(`practice.html's checkWordListsTypeable() did not report an untypeable target planted in\n`
        + `            level "${level}": it checked ${probed.checked} spelling(s) (expected ${wanted + 2}) and named it\n`
        + `            in ${named.length} failure(s).\n`
        + `            The probe is "${UNTYPEABLE_PROBE}", and it is untypeable because of the escape rule\n`
        + `            the spec pins ("ass -> as"): the only key sequence that produces the\n`
        + '            literal text "as" is "ass", the hint speller emits "as", and the engine\n'
        + '            turns that final "s" into a tone — so the replay owes "á" and the guard\n'
        + '            owes a failure. Getting no failure means the comparison inside\n'
        + '            checkWordListsTypeable() no longer compares, or that level is skipped —\n'
        + '            and then the "168 spellings replay to their target" line this file\n'
        + '            PRINTS on a green run is not a thing anyone checked.\n'
        + `            If the escape rule itself changed, ${VECTOR_PATH}\n`
        + '            says so first; pick a new probe in the same commit.');
    }
  }
  return { ...out, entries };
}

function runJsVector(js, v) {
  js.resetTelexState();
  if (v.section === 'transform') {
    let buf = '';
    for (const ch of v.input) buf = js.transform(buf, ch);
    return buf;
  }
  let st = { committed: '', buffer: '' };
  for (const ch of v.input) st = js.applyKey(st.committed, st.buffer, ch);
  return st.committed + st.buffer;
}

// ===========================================================================
// THE SCORING LAYER — practice.html's real keydown handler, driven headless
// ===========================================================================
// The engine is the well-guarded half of this project: 266 conformance vectors,
// two implementations swept against each other, a break rule compared key by
// key. The half that decides whether a keystroke was RIGHT had nothing. Not one
// line anywhere executed unitStatuses(), syllableStatus(), canStillFinish(),
// isRepairable(), recordKeystroke(), updateStats(), the wordEnded latch, the
// Space-after-completion gesture or setStuckNotice() — and four of the last five
// defects in this project lived in exactly those functions:
//
//   round 1  perfect typing scored ~33%: the scored predicate was a prefix test,
//            and a composing input method does not walk through its target one
//            finished character at a time.
//   round 1  the fix overshot: scoring on bare letters alone let `dduwowngs`
//   (again) ("đướng" for "đường") score 100% — the one thing the app teaches,
//            wrong, called correct.
//   round 3  the wordEnded latch was set by completion and cleared only by
//            loading another word, so Backspace after a completed word left the
//            display on the old target while the next keystroke was scored
//            against the next one.
//   round 4  the rising edge was taken on the whole text rather than per unit,
//            so every slip after the first was free; the denominator kept
//            growing, and a four-mistake run read better than a one-mistake run.
//   round 5  units were paired by CHARACTER INDEX, so one length-changing slip
//            (a stray letter, a missing space) knocked every later unit out of
//            alignment and charged the same mistake five times when it was typed
//            early and once when it was typed late.
//
// Every one of those is a row in the tables below. They are TABLES on purpose:
// the next defect in this layer should cost a maintainer one row, not one test.
//
// The handler is DRIVEN, not re-implemented and not copied. practice.html's
// entire <script> is evaluated under the DOM stub below and the keydown listener
// it registers is called with synthetic events — so what these cases exercise is
// the shipped path, including applyKey(), the unit walk, the edge charge, the
// stats, the border and the notice. A copy would drift, which is the failure
// this whole file exists to catch.

// The slice. One marker pair, asserted to be unique: practice.html is a single
// self-contained page with exactly one script, and if that ever stops being true
// the slice silently becomes "some of the page" — so it fails instead.
const SCRIPT_OPEN = '<script>';
const SCRIPT_CLOSE = '</script>';

// Markers WITHIN the slice, so an empty or truncated cut cannot read as "no
// cases to run". These are the declarations the cases below actually drive; each
// is named in the failure so the fix is a lookup, not a search.
const SCORING_REQUIRED_TEXT = [
  ["els.display.addEventListener('keydown'", 'the keydown handler these cases drive'],
  ['function unitStatuses(', 'the unit walk'],
  ['function recordKeystroke(', 'the per-unit rising edge'],
  ['function updateStats(', 'the WPM/accuracy readout'],
  ['function canStillFinish(', 'reachability — "can the target still be reached?"'],
  ['function isRepairable(', 'the wrong-but-recoverable probe'],
  ['function setStuckNotice(', 'the dead-end notice'],
  ['const PAINT = {', 'the palette the paint reader learns its markup from'],
  ['function charVerdict(', 'the three-way per-character verdict the paint rows pin'],
  ['function updatePracticeDisplay(', 'the paint loop'],
  ['function undoKey(', 'Backspace undoes a KEYSTROKE, not a character'],
  ['function composeKeys(', 'the keystroke-log replay that undo is built on'],
];

function countOf(hay, needle) {
  let n = 0;
  for (let i = hay.indexOf(needle); i >= 0; i = hay.indexOf(needle, i + needle.length)) n++;
  return n;
}

function practiceScript(html) {
  const opens = countOf(html, SCRIPT_OPEN), closes = countOf(html, SCRIPT_CLOSE);
  if (opens !== 1 || closes !== 1) {
    die(`practice.html has ${opens} "${SCRIPT_OPEN}" and ${closes} "${SCRIPT_CLOSE}" — the scoring harness\n`
      + '            slices THE script and can only do that while there is exactly one.\n'
      + '            Splitting the page into several scripts means saying which one holds\n'
      + '            the keydown handler; teach practiceScript() the new shape rather than\n'
      + '            letting it cut an arbitrary one.');
  }
  const from = html.indexOf(SCRIPT_OPEN) + SCRIPT_OPEN.length;
  const to = html.indexOf(SCRIPT_CLOSE);
  if (to < from) die(`practice.html's "${SCRIPT_CLOSE}" comes before "${SCRIPT_OPEN}"`);
  const src = html.slice(from, to);
  const missing = SCORING_REQUIRED_TEXT.filter(([needle]) => !src.includes(needle));
  if (missing.length) {
    die('the practice.html script slice is missing:\n'
      + missing.map(([needle, what]) => `              ${needle}   (${what})`).join('\n') + '\n'
      + '            Either the markers drifted or one of these was renamed. Renaming is\n'
      + '            fine — say so here in the same commit. What is NOT fine is this file\n'
      + '            quietly running zero scoring cases and still printing PASS: the\n'
      + '            scoring layer had no automated coverage at all for five rounds, and\n'
      + '            four of the five rounds\' defects lived in it.');
  }
  return src;
}

// ---------------------------------------------------------------------------
// The DOM stub. Small on purpose: it implements the handful of APIs the page
// really uses and nothing else, so an unimplemented one is a loud TypeError
// naming itself rather than a silently wrong verdict.
//
// It is a real little tree — body, children, classes — because the page reads
// its own output back: findKbKey() looks up `.kb-key` by data-char, and the
// next-key hint is READ OFF the keyboard it just painted, which is what makes
// the "no strands" assertion free (see checkScoring).
// ---------------------------------------------------------------------------
function makeDom() {
  let doc;
  const mkEl = (tag) => {
    const el = {
      tagName: String(tag || 'div').toUpperCase(),
      children: [], parent: null, classes: [], dataset: {}, listeners: new Map(),
      _text: '', _html: '', hidden: false, value: '', checked: false, style: {},
      get className() { return el.classes.join(' '); },
      set className(v) { el.classes = String(v).split(/\s+/).filter(Boolean); },
      get textContent() { return el._text; },
      set textContent(v) { el._text = String(v); el.children = []; },
      get innerHTML() { return el._html; },
      set innerHTML(v) {
        el._html = String(v);
        if (v === '') { for (const c of el.children) c.parent = null; el.children = []; }
      },
      appendChild(c) { c.parent = el; el.children.push(c); return c; },
      removeChild(c) { const i = el.children.indexOf(c); if (i >= 0) el.children.splice(i, 1); c.parent = null; return c; },
      addEventListener(type, fn) {
        if (!el.listeners.has(type)) el.listeners.set(type, []);
        el.listeners.get(type).push(fn);
      },
      focus() { doc.activeElement = el; },
      querySelector(sel) { return qsa(el, sel)[0] || null; },
      querySelectorAll(sel) { return qsa(el, sel); },
      closest() { return null; },
    };
    el.classList = {
      add: (...cs) => { for (const c of cs) if (!el.classes.includes(c)) el.classes.push(c); },
      remove: (...cs) => { el.classes = el.classes.filter(c => !cs.includes(c)); },
      contains: (c) => el.classes.includes(c),
      toggle: (c, on) => {
        const has = el.classes.includes(c), want = on === undefined ? !has : !!on;
        if (want && !has) el.classes.push(c);
        else if (!want && has) el.classes = el.classes.filter(x => x !== c);
      },
    };
    return el;
  };
  // Only the selector shapes practice.html uses: ".a" and ".a.b".
  const matches = (el, sel) => sel.split('.').filter(Boolean).every(c => el.classes.includes(c));
  const qsa = (root, sel) => {
    const out = [];
    (function walk(n) { for (const c of n.children) { if (matches(c, sel)) out.push(c); walk(c); } })(root);
    return out;
  };
  const byId = new Map();
  const body = mkEl('body');
  doc = {
    body,
    activeElement: null,
    getElementById(id) {
      if (!byId.has(id)) { const el = mkEl('div'); el.id = id; byId.set(id, el); body.appendChild(el); }
      return byId.get(id);
    },
    querySelector(sel) { return qsa(body, sel)[0] || null; },
    querySelectorAll(sel) { return qsa(body, sel); },
    createElement(tag) { return mkEl(tag); },
    addEventListener() {},
  };
  // The controls the page DERIVES its settings from. Every toggle on, level
  // "easy" — i.e. the shipped defaults, so the cases below exercise the
  // configuration a first-time typist actually meets (auto-advance included).
  for (const id of ['show-hint', 'auto-advance', 'show-kb', 'show-next']) doc.getElementById(id).checked = true;
  doc.getElementById('level').value = 'easy';
  for (const cls of ['target-hint', 'toggle-row']) {
    const el = mkEl('div');
    el.className = cls;
    body.appendChild(el);
  }
  return doc;
}

