const scored = (engine) => results.filter(r => ran[engine] && applies(engine, r.vector.section));

const failures = [];
for (const r of results) {
  for (const e of ENGINES) {
    if (!ran[e] || !applies(e, r.vector.section)) continue;
    if (r[e] !== r.vector.expected) {
      failures.push({ ...r.vector, engine: e.toUpperCase().padEnd(4), actual: r[e] });
    }
  }
}
const jsPass = scored('js').filter(r => r.js === r.vector.expected).length;
const ahkPass = scored('ahk').filter(r => r.ahk === r.vector.expected).length;
const rustPass = scored('rust').filter(r => r.rust === r.vector.expected).length;

// Drift is engine-vs-engine, independent of the spec: two engines can both be
// wrong the same way (that is a spec bug) or wrong in different ways (that is
// drift). Only pairs where BOTH engines are a spec for the section — comparing
// an answer against an engine that was never asked is not drift, it is a
// category error.
const passOf = { js: jsPass, ahk: ahkPass, rust: rustPass };

// One tally, built from the counts the checks produced, used by every verdict
// below. Each engine carries its OWN denominator — they are not all answering
// the same number of questions any more, and printing a shared one would be a
// quiet lie about coverage.
const tally = ENGINES
  .map(e => (ran[e] ? `${e.toUpperCase()} ${passOf[e]}/${checked(e)}` : `${e.toUpperCase()} UNVERIFIED`))
  .join(', ');

const PAIRS = [['js', 'ahk'], ['js', 'rust'], ['ahk', 'rust']];
const engineCount = ENGINES.filter(e => ran[e]).length;
const drift = results.flatMap(r => PAIRS
  .filter(([a, b]) => ran[a] && ran[b]
    && applies(a, r.vector.section) && applies(b, r.vector.section)
    && r[a] !== r[b])
  .map(([a, b]) => ({ vector: r.vector, a: a.toUpperCase(), av: r[a], b: b.toUpperCase(), bv: r[b] })));
const wordListBroken = wordList.failures.length > 0;
const scoringBroken = scoring.failures.length > 0;
const allGood = failures.length === 0 && !embeddedStale && !wordListBroken && !scoringBroken;

// What a green run is entitled to CLAIM. Every number here is counted by the
// check that produced it, not by the reporter, so the line cannot say more than
// was actually done.
const c = scoring.counts;
function scoringLines(indent) {
  return [
    `${indent}${wordList.checked} WORD_LISTS spellings replay to their target `
      + `(${wordList.entries} targets x both hinted orders)`,
    `${indent}scoring layer, through practice.html's real keydown handler:`,
    `${indent}  ${c.replays} flawless replays (${c.targets} targets x both spelling orders) score 100% with 0 errors`,
    `${indent}  ${c.positions} slip(s) cost the same typed early as typed late, length-changing ones included`,
    `${indent}  ${c.cases} keystroke case(s), ${c.noops} swallowed-key case(s), ${c.severities} severity comparison(s)`,
    `${indent}  no strands: every state the scorer accepts still lights a next key`,
    `${indent}  the painted characters were read at ${c.paintStates} states: what the display marks`,
    `${indent}    is exactly what the scorer calls broken, and a flawless run marks nothing`,
  ];
}

if (allGood && ahkRan && rustRan) {
  console.log(`PASS  ${vectors.length} vectors — all three engines: ${tally}`);
  console.log(`      practice.html engine + VietDvorak.ahk Transform() + vietdvorak-core`);
  console.log(`      all match ${VECTOR_PATH}`);
  // Denominators differ on purpose; say so once here rather than let a reader
  // wonder whether a smaller number means something was skipped.
  for (const s of SECTIONS) {
    const only = SECTION_ENGINES[s];
    if (only.length < ENGINES.length) {
      const n = vectors.filter(v => v.section === s).length;
      console.log(`      @section ${s}: ${n} vector(s), ${only.join(' + ')} only — by spec, see the file header`);
    }
  }
  console.log(`      AutoHotkey: ${found.exe}`);
  console.log('      embedded self-test vectors are in sync');
  for (const l of scoringLines('      ')) console.log(l);
  for (const n of ahkNotes) console.log(`      ${n}`);
  for (const n of harnessNotes) console.log(`      NOTE  ${n}`);
  process.exit(0);
}

if (allGood) {
  // Every vector that RAN agrees with the spec, but at least one engine did not
  // run. Name which, and keep the exit non-zero — see loudSkip() and the header.
  const unverified = ENGINES.filter(e => !ran[e]).map(e => e.toUpperCase()).join(' + ');
  console.log(`PARTIAL  ${unverified} side UNVERIFIED — ${tally}`);
  console.log(`         ${engineCount} of 3 engines ran and match ${VECTOR_PATH}`);
  console.log('         embedded self-test vectors are in sync');
  for (const l of scoringLines('         ')) console.log(l);
  if (!ahkRan) {
    console.log('         the syllable-break rule was NOT checked either: it lives in');
    console.log('         VietDvorak.ahk and is swept by running it.');
  }
  for (const n of harnessNotes) console.log(`         NOTE  ${n}`);
  process.exit(1);
}

// Something is wrong. Print EVERY problem that is present before exiting: these
// are independent guards, and reporting only the first would send a maintainer
// round the loop once per fault.
if (wordListBroken) {
  console.error(`UNTYPEABLE  ${wordList.failures.length} of ${wordList.checked} WORD_LISTS spelling(s)`
    + ' do not replay to their target');
  console.error('');
  for (const f of wordList.failures.slice(0, 20)) console.error(`      ${f}`);
  if (wordList.failures.length > 20) {
    console.error(`      ... and ${wordList.failures.length - 20} more`);
  }
  console.error('');
  console.error('      Every WORD_LISTS entry in practice.html must be reachable THROUGH the');
  console.error('      engine: the trainer prints a key sequence as the hint and then requires');
  console.error('      the typed text to equal the target exactly, so a target the engine can');
  console.error('      never produce is a level that can never be completed. Both hinted');
  console.error('      orders are replayed, because targetKeyHint() prints both.');
  console.error('      No conformance vector can catch this — the vectors pin the ENGINE, and');
  console.error('      here the engine is doing exactly what the spec says.');
  console.error('      Usual causes: a target spelled against TONE_PLACEMENT_MODERN ("khỏe"');
  console.error(`      while ${VECTOR_PATH}`);
  console.error('      says "khoer -> khoẻ"), or a rule change that moved a mark the word');
  console.error('      list still spells the old way. Fix the list, or the rule — not this.');
  console.error('');
}

if (scoringBroken) {
  console.error(`MISSCORED  ${scoring.failures.length} scoring assertion(s) failed — practice.html's keydown`
    + ' handler, driven headless');
  console.error('');
  for (const f of scoring.failures.slice(0, 20)) console.error(`      ${f}`);
  if (scoring.failures.length > 20) {
    console.error(`      ... and ${scoring.failures.length - 20} more`);
  }
  console.error('');
  console.error('      These drive the REAL handler in practice.html under a DOM stub — the');
  console.error('      same applyKey(), the same unit walk, the same rising-edge charge the');
  console.error('      typist gets. No conformance vector can reach any of it: the vectors pin');
  console.error('      the ENGINE, and here the engine is doing exactly what the spec says while');
  console.error('      the app disagrees about whether the typist did.');
  console.error('      Four of the last five defects in this project lived in this layer. Each');
  console.error('      of the five is a row in SCORING_CASES / POSITION_CASES / SEVERITY_CASES');
  console.error('      in check-parity.mjs — start by reading the row that failed and the');
  console.error('      comment above its table, which says which round it is from.');
  console.error('');
}

if (embeddedStale) {
  const diff = blockDiff(html.slice(genRegion.from, genRegion.to), block);
  console.error('STALE practice.html\'s embedded self-test vectors no longer match');
  console.error(`      ${VECTOR_PATH}`);
  console.error('');
  printBlockDiff(diff, console.error);
  console.error('');
  console.error('      If that is a regeneration, run:  node check-parity.mjs --sync-selftests');
  console.error('      If a row above was edited by hand inside practice.html, sync will');
  console.error('      DISCARD it — put the change in the spec instead.');
  console.error('');
}

// Nothing left to tabulate: the vectors themselves are all green and what failed
// was one of the guards above.
if (failures.length === 0) {
  console.error(`      (the engines themselves pass: ${tally})`);
  process.exit(1);
}

console.error(`FAIL  ${tally} — ${failures.length} mismatch(es)\n`);
const wIn = Math.max(...failures.map(f => f.input.length), 5);
const wSec = Math.max(...failures.map(f => f.section.length), 7);
const wExp = Math.max(...failures.map(f => f.expected.length), 8);
console.error(`  ${'line'.padStart(5)}  ${'section'.padEnd(wSec)}  ${'input'.padEnd(wIn)}  engine  ${'expected'.padEnd(wExp)}  actual`);
for (const f of failures) {
  console.error(`  ${String(f.lineNo).padStart(5)}  ${f.section.padEnd(wSec)}  ${f.input.padEnd(wIn)}  ${f.engine}     ${f.expected.padEnd(wExp)}  ${f.actual}`);
  // Same glyphs, different code points = a Unicode normalisation problem, not a
  // logic bug. Say so explicitly instead of leaving two identical-looking strings.
  if (typeof f.actual === 'string' && f.actual.normalize('NFC') === f.expected.normalize('NFC')) {
    console.error('         ^ differs only by Unicode normalisation:');
    console.error(`           expected ${codePoints(f.expected)}`);
    console.error(`           actual   ${codePoints(f.actual)}`);
  }
}

if (drift.length) {
  console.error(`\n  The engines also disagree with EACH OTHER on ${drift.length} pair(s):`);
  for (const d of drift.slice(0, 10)) {
    console.error(`    ${d.vector.input.padEnd(wIn)}  ${d.a} ${JSON.stringify(d.av)}  vs  ${d.b} ${JSON.stringify(d.bv)}`);
  }
  if (drift.length > 10) console.error(`    ... and ${drift.length - 10} more`);
  console.error('  That is real drift: whatever the spec says, one of them is already wrong.');
  if (rustRan && rustPass < vectors.length) {
    console.error('');
    console.error('  While the Rust port is in progress, RUST rows are EXPECTED to be red and');
    console.error('  are not drift in the usual sense — they are the port not being finished.');
    console.error('  What matters is that the JS/AHK pair stays green: if that pair goes red,');
    console.error('  something broke in the shipped engines and the port is not the cause.');
  }
}

console.error(`\n  ${VECTOR_PATH} is the spec. If the new behaviour is intended,`);
console.error('  change the spec and EVERY engine in the same commit.');
